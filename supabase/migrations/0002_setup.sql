-- Starter app: run this once in Supabase → SQL Editor → New query → Run

create table if not exists public.todos (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title       text not null check (char_length(title) between 1 and 200),
  is_done     boolean not null default false,
  created_at  timestamptz not null default now()
);

create index if not exists todos_user_id_idx on public.todos (user_id);

-- Row Level Security: each signed-in user sees and changes only their own rows.
alter table public.todos enable row level security;

drop policy if exists "Read own todos"   on public.todos;
drop policy if exists "Insert own todos" on public.todos;
drop policy if exists "Update own todos" on public.todos;
drop policy if exists "Delete own todos" on public.todos;

create policy "Read own todos"   on public.todos for select to authenticated using (auth.uid() = user_id);
create policy "Insert own todos" on public.todos for insert to authenticated with check (auth.uid() = user_id);
create policy "Update own todos" on public.todos for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Delete own todos" on public.todos for delete to authenticated using (auth.uid() = user_id);
