create or replace function public.orders_sms()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  s jsonb; ev jsonb; lang text; ph text; kind text;
begin
  select value into s from public.site_settings where key = 'sms';
  if s is null or coalesce((s->>'on')::boolean, false) is not true then return null; end if;
  ev := coalesce(s->'events', '{}'::jsonb);
  lang := case when s->>'lang' = 'bn' then 'bn' else 'en' end;
  if tg_op = 'INSERT' then
    ph := public.sms_phone(new.phone);
    if ph is not null and coalesce((ev->>'placed')::boolean, false) then
      insert into public.sms_outbox (phone, body, kind, order_id) values (ph, public.sms_text('placed', new, lang), 'placed', new.id);
    end if;
    if coalesce((ev->>'shop_new')::boolean, false) then
      select public.sms_phone(coalesce(nullif(sd.phone_public, ''), p.phone)) into ph
        from public.profiles p left join public.seller_details sd on sd.user_id = p.id where p.id = new.seller_id;
      if ph is not null then
        insert into public.sms_outbox (phone, body, kind, order_id) values (ph, public.sms_text('shop_new', new, lang), 'shop_new', new.id);
      end if;
    end if;
  elsif new.status is distinct from old.status and new.status in ('confirmed', 'shipped', 'delivered', 'cancelled') then
    kind := new.status;
    ph := public.sms_phone(new.phone);
    if ph is not null and coalesce((ev->>kind)::boolean, false) then
      insert into public.sms_outbox (phone, body, kind, order_id) values (ph, public.sms_text(kind, new, lang), kind, new.id);
    end if;
  end if;
  return null;
exception when others then
  return null;   -- an SMS problem must never stop an order
end; $$;
revoke execute on function public.orders_sms() from public, anon, authenticated;

drop trigger if exists zz_orders_sms on public.orders;
create trigger zz_orders_sms after insert or update of status on public.orders
  for each row execute function public.orders_sms();

-- 4. For the send-alerts function (server only) ----------------------------------------------------------------------------
create or replace function public.take_pending_sms(p_limit integer default 50)
returns setof public.sms_outbox language plpgsql security definer set search_path = ''
as $$
begin
  update public.sms_outbox set status = 'skipped', error = coalesce(error, 'Too old to send')
   where status = 'pending' and created_at < now() - interval '2 hours';
  return query
  update public.sms_outbox set attempts = attempts + 1
   where id in (select id from public.sms_outbox where status = 'pending' and attempts < 3
                order by created_at limit greatest(1, least(coalesce(p_limit, 50), 100)) for update skip locked)
  returning *;
end; $$;
revoke execute on function public.take_pending_sms(integer) from public, anon, authenticated;
grant  execute on function public.take_pending_sms(integer) to service_role;

create or replace function public.sms_sent(p_id bigint, p_ok boolean, p_ref text default null, p_error text default null)
returns void language sql security definer set search_path = ''
as $$
  update public.sms_outbox
     set status = case when p_ok then 'sent' when attempts >= 3 then 'failed' else 'pending' end,
         sent_at = case when p_ok then now() end, provider_ref = left(p_ref, 100), error = left(p_error, 300)
   where id = p_id;
$$;
revoke execute on function public.sms_sent(bigint, boolean, text, text) from public, anon, authenticated;
grant  execute on function public.sms_sent(bigint, boolean, text, text) to service_role;

-- 5. Admin: test message and the list of recent SMS (Master admin and Co-admins) ------------------------------------------
create or replace function public.admin_test_sms(p_phone text)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare ph text; n bigint; lang text;
begin
  if not public.has_staff_role(array['master_admin', 'co_admin']) then raise exception 'Only Master admin or Co-admins can do this'; end if;
  ph := public.sms_phone(p_phone);
  if ph is null then raise exception 'Write a Bangladesh mobile number like 01712345678'; end if;
  if (select count(*) from public.sms_outbox where kind = 'test' and created_at > now() - interval '1 hour') >= 10 then
    raise exception 'Too many test messages this hour. Try again later.';
  end if;
  select case when value->>'lang' = 'bn' then 'bn' else 'en' end into lang from public.site_settings where key = 'sms';
  insert into public.sms_outbox (phone, body, kind)
  values (ph, case when lang = 'bn' then 'RGBKart: এটি একটি পরীক্ষামূলক SMS। SMS ঠিকমতো কাজ করছে।'
                   else 'RGBKart: This is a test SMS. Order text messages are working.' end, 'test')
  returning id into n;
  return n;
end; $$;
revoke execute on function public.admin_test_sms(text) from public, anon;
grant  execute on function public.admin_test_sms(text) to authenticated;

create or replace function public.admin_sms_log(p_limit integer default 50)
returns table (id bigint, created_at timestamptz, phone text, kind text, status text, error text, body text, order_no text)
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.has_staff_role(array['master_admin', 'co_admin']) then raise exception 'Only Master admin or Co-admins can do this'; end if;
  return query
  select s.id, s.created_at, s.phone, s.kind, s.status, s.error, s.body, o.order_no
    from public.sms_outbox s left join public.orders o on o.id = s.order_id
   order by s.id desc limit greatest(1, least(coalesce(p_limit, 50), 200));
end; $$;
revoke execute on function public.admin_sms_log(integer) from public, anon;
grant  execute on function public.admin_sms_log(integer) to authenticated;

