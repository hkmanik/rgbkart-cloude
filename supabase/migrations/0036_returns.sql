-- Returns (plan 4.6).
-- After an order is delivered, the customer can ask to return an item within the product's return days
-- (the seller's "Returns" setting on the product: no returns / 3 / 7 / 15 / 30 days, saved on the order line when ordered).
-- The customer gives the reason, refund or exchange, details and up to 3 photos (private: only the customer, the shop and staff see them).
-- The shop accepts (and arranges the pickup), declines with a reason, and marks "Item received back" (stock goes back).
-- Money: Cash on Delivery only and RGBKart never holds money, so the shop pays any refund to the customer directly.
-- Run once in Supabase → SQL Editor, AFTER 0035_bangla_fill_more.sql (or 0033). Safe to run again.

-- 1. Return days saved on each order line --------------------------------------------------------------------
alter table public.order_items add column if not exists return_days integer;
create or replace function public.order_items_return_days()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if new.return_days is null then
    new.return_days := coalesce((select case p.return_policy when '3_days' then 3 when '7_days' then 7 when '15_days' then 15 when '30_days' then 30 else 0 end
                                 from public.products p where p.id = new.product_id), 0);
  end if;
  return new;
end; $$;
drop trigger if exists order_items_return_days on public.order_items;
create trigger order_items_return_days before insert on public.order_items for each row execute function public.order_items_return_days();
update public.order_items i set return_days = case p.return_policy when '3_days' then 3 when '7_days' then 7 when '15_days' then 15 when '30_days' then 30 else 0 end
  from public.products p where p.id = i.product_id and i.return_days is null;
update public.order_items set return_days = 0 where return_days is null;

-- 2. Return requests ----------------------------------------------------------------------------------------------
create table if not exists public.return_requests (
  id             bigint generated by default as identity primary key,
  order_id       bigint not null references public.orders (id) on delete cascade,
  order_item_id  bigint not null references public.order_items (id) on delete cascade,
  product_id     bigint references public.products (id) on delete set null,
  seller_id      uuid not null references public.profiles (id) on delete cascade,
  customer_id    uuid not null references auth.users (id) on delete cascade,
  qty            integer not null check (qty between 1 and 99),
  reason         text not null check (reason in ('damaged', 'wrong_item', 'not_as_described', 'missing_parts', 'size_fit', 'quality', 'changed_mind', 'other')),
  wants          text not null default 'refund' check (wants in ('refund', 'exchange')),
  details        text check (details is null or char_length(details) <= 1000),
  photos         text[] not null default '{}' check (cardinality(photos) <= 3),
  status         text not null default 'requested' check (status in ('requested', 'approved', 'rejected', 'received', 'cancelled')),
  seller_note    text check (seller_note is null or char_length(seller_note) <= 500),
  decided_at     timestamptz,
  completed_at   timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists return_requests_seller on public.return_requests (seller_id, status, created_at desc);
create index if not exists return_requests_customer on public.return_requests (customer_id, created_at desc);
create index if not exists return_requests_item on public.return_requests (order_item_id);

alter table public.return_requests enable row level security;
revoke all on public.return_requests from anon, authenticated;
grant select on public.return_requests to authenticated;     -- changes only through the functions below
drop policy if exists "Own returns, shop and staff" on public.return_requests;
create policy "Own returns, shop and staff" on public.return_requests for select to authenticated
  using (customer_id = auth.uid() or seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));

-- Private photo folder: the customer uploads into return-photos/<own id>/…; customer, shop of the return and staff can view
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('return-photos', 'return-photos', false, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
drop policy if exists "Customers upload return photos" on storage.objects;
create policy "Customers upload return photos" on storage.objects for insert to authenticated
  with check (bucket_id = 'return-photos' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Return photos for customer, shop and staff" on storage.objects;
create policy "Return photos for customer, shop and staff" on storage.objects for select to authenticated
  using (bucket_id = 'return-photos' and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.has_staff_role(array['master_admin', 'co_admin', 'editor'])
    or exists (select 1 from public.return_requests r where r.seller_id = auth.uid() and name = any (r.photos))));
drop policy if exists "Customers delete own return photos" on storage.objects;
create policy "Customers delete own return photos" on storage.objects for delete to authenticated
  using (bucket_id = 'return-photos' and (storage.foldername(name))[1] = auth.uid()::text);

-- 3. Customer asks for a return ---------------------------------------------------------------------------------
create or replace function public.request_return(p_item bigint, p_qty integer, p_reason text, p_wants text default 'refund',
                                                 p_details text default null, p_photos text[] default '{}')
returns bigint language plpgsql security definer set search_path = ''
as $$
declare it record; o record; done int; d text; ph text[]; rid bigint;
begin
  if auth.uid() is null then raise exception 'Please sign in first'; end if;
  select * into it from public.order_items where id = p_item;
  select * into o from public.orders where id = it.order_id;
  if it.id is null or o.customer_id <> auth.uid() then raise exception 'Order not found'; end if;
  if o.status <> 'delivered' then raise exception 'You can ask for a return after the order is delivered'; end if;
  if coalesce(it.return_days, 0) = 0 then raise exception 'This item cannot be returned (the shop does not take returns for it)'; end if;
  if coalesce(o.delivered_at, o.updated_at) + make_interval(days => it.return_days) < now() then
    raise exception 'The return time for this item has ended (% days after delivery)', it.return_days;
  end if;
  if exists (select 1 from public.return_requests where order_item_id = p_item and status in ('requested', 'approved')) then
    raise exception 'You already asked to return this item';
  end if;
  select coalesce(sum(qty), 0) into done from public.return_requests where order_item_id = p_item and status = 'received';
  if p_qty is null or p_qty < 1 or p_qty > it.qty - done then raise exception 'Choose how many to return (1 to %)', it.qty - done; end if;
  if p_reason not in ('damaged', 'wrong_item', 'not_as_described', 'missing_parts', 'size_fit', 'quality', 'changed_mind', 'other') then raise exception 'Choose a reason'; end if;
  if coalesce(p_wants, 'refund') not in ('refund', 'exchange') then raise exception 'Choose refund or exchange'; end if;
  d := nullif(trim(regexp_replace(coalesce(p_details, ''), '\s+', ' ', 'g')), '');
  if char_length(d) > 1000 then raise exception 'Please keep the details under 1000 letters'; end if;
  if p_reason = 'other' and d is null then raise exception 'Please tell the shop what is wrong'; end if;
  ph := coalesce((select array_agg(x) from unnest(coalesce(p_photos, '{}')) x where x like auth.uid()::text || '/%'), '{}');
  if cardinality(ph) > 3 then raise exception 'Up to 3 photos'; end if;
  insert into public.return_requests (order_id, order_item_id, product_id, seller_id, customer_id, qty, reason, wants, details, photos)
  values (o.id, it.id, it.product_id, o.seller_id, auth.uid(), p_qty, p_reason, coalesce(p_wants, 'refund'), d, ph)
  returning id into rid;
  return rid;
end; $$;
revoke execute on function public.request_return(bigint, integer, text, text, text, text[]) from public, anon;
grant  execute on function public.request_return(bigint, integer, text, text, text, text[]) to authenticated;

create or replace function public.cancel_return(p_return bigint)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  update public.return_requests set status = 'cancelled', updated_at = now()
   where id = p_return and customer_id = auth.uid() and status = 'requested';
  if not found then raise exception 'This return can no longer be cancelled'; end if;
end; $$;
revoke execute on function public.cancel_return(bigint) from public, anon;
grant  execute on function public.cancel_return(bigint) to authenticated;

-- 4. Shop (or staff) decides: approved → received, or rejected ------------------------------------------------
create or replace function public.decide_return(p_return bigint, p_status text, p_note text default null)
returns void language plpgsql security definer set search_path = ''
as $$
declare r record; it record; n text := nullif(trim(coalesce(p_note, '')), '');
begin
  select * into r from public.return_requests where id = p_return for update;
  if r.id is null or (r.seller_id <> auth.uid() and not public.has_staff_role(array['master_admin', 'co_admin'])) then raise exception 'Return not found'; end if;
  if p_status = 'approved' and r.status <> 'requested' then raise exception 'Only a new request can be accepted'; end if;
  if p_status = 'rejected' and r.status not in ('requested', 'approved') then raise exception 'This return is already closed'; end if;
  if p_status = 'rejected' and n is null then raise exception 'Tell the customer why you are declining'; end if;
  if p_status = 'received' and r.status <> 'approved' then raise exception 'Accept the return first'; end if;
  if p_status not in ('approved', 'rejected', 'received') then raise exception 'Unknown step'; end if;
  update public.return_requests set status = p_status, seller_note = coalesce(n, seller_note), updated_at = now(),
         decided_at = case when p_status in ('approved', 'rejected') then now() else decided_at end,
         completed_at = case when p_status = 'received' then now() else completed_at end
   where id = r.id;
  if p_status = 'received' then           -- the item is back in the shop: put the stock back
    select * into it from public.order_items where id = r.order_item_id;
    if it.variation_id is not null then
      update public.product_variations set stock = stock + r.qty where id = it.variation_id;
    else
      update public.products set stock = stock + r.qty where id = it.product_id and manage_stock;
    end if;
  end if;
end; $$;
revoke execute on function public.decide_return(bigint, text, text) from public, anon;
grant  execute on function public.decide_return(bigint, text, text) to authenticated;

-- 5. Alerts ---------------------------------------------------------------------------------------------------------
create or replace function public.alerts_returns()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare t text; ono text;
begin
  select title into t from public.order_items where id = new.order_item_id;
  select order_no into ono from public.orders where id = new.order_id;
  if tg_op = 'INSERT' then
    perform public.notify(new.seller_id, 'return_new', format('Return request: %s', left(coalesce(t, 'item'), 80)),
      format('Order %s · %s × · %s%s', ono, new.qty, replace(new.reason, '_', ' '), coalesce(' · ' || new.details, '')), 'seller.html#returns', 'return:' || new.id);
  elsif new.status is distinct from old.status and new.status in ('approved', 'rejected', 'received') then
    perform public.notify(new.customer_id, 'return_' || new.status,
      case new.status when 'approved' then 'Your return was accepted' when 'rejected' then 'Your return was declined' else 'The shop received your return' end,
      coalesce(new.seller_note, case new.status when 'approved' then 'The shop will contact you about sending the item back.'
                                                 when 'received' then 'The shop has the item back and will settle the refund or exchange with you.' else '' end),
      'orders.html', 'return:' || new.id);
  end if;
  return null;
end; $$;
drop trigger if exists alerts_returns on public.return_requests;
create trigger alerts_returns after insert or update of status on public.return_requests for each row execute function public.alerts_returns();

select to_regclass('public.return_requests') is not null as returns_ready,
       (select count(*) from public.order_items where return_days > 0) as returnable_order_lines;
