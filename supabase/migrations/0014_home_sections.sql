-- Home page sections (plan 5.9): the product rows on the home page, managed in Admin → Home page.
-- Run once in Supabase → SQL Editor. Safe to run again (default sections are only added the first time).
--
-- Section types:
--   featured   Featured products (paid Featured listings)
--   deals      Deals of the Day (products with an active sale price)
--   newest     New arrivals
--   pre_owned  Pre-owned products
--   free_delivery  Products with free delivery
--   category   Products from one category (and its sub-categories)

create table if not exists public.home_sections (
  id           bigint generated by default as identity primary key,
  title        text not null check (char_length(trim(title)) between 2 and 60),
  subtitle     text check (subtitle is null or char_length(subtitle) <= 120),
  section_type text not null check (section_type in ('featured', 'deals', 'newest', 'pre_owned', 'free_delivery', 'category')),
  category_id  bigint references public.categories (id) on delete cascade,
  item_count   integer not null default 12 check (item_count in (6, 12, 18, 24)),
  sort_order   integer not null default 0,
  is_active    boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  check (section_type <> 'category' or category_id is not null)
);

alter table public.home_sections enable row level security;
revoke all on public.home_sections from anon, authenticated;
grant select on public.home_sections to anon, authenticated;
grant insert, update, delete on public.home_sections to authenticated;

drop policy if exists "Anyone reads active sections" on public.home_sections;
create policy "Anyone reads active sections" on public.home_sections for select to anon, authenticated
  using (is_active or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));
drop policy if exists "Staff manage sections" on public.home_sections;
create policy "Staff manage sections" on public.home_sections for all to authenticated
  using (public.has_staff_role(array['master_admin', 'co_admin', 'editor']))
  with check (public.has_staff_role(array['master_admin', 'co_admin', 'editor']));

