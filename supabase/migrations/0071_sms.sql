-- 0071 SMS order updates through BulkSMSBD (owner, 30 Oct 2026).
-- Nothing is sent until you switch SMS on in Admin → Orders → SMS messages (it starts OFF).
-- How it works: order events put a short text in the sms_outbox; the send-alerts function (every 5 minutes, or at once
-- after "Send test SMS") sends them through BulkSMSBD. Needs the Edge Function secrets BULKSMSBD_API_KEY and
-- BULKSMSBD_SENDER_ID (see the setup steps). Safe to run more than once.

-- 1. Settings (Admin → Orders → SMS messages) -----------------------------------------------------------------------------
insert into public.site_settings (key, value) values ('sms', jsonb_build_object(
  'on', false, 'lang', 'en',
  'events', jsonb_build_object('placed', true, 'confirmed', false, 'shipped', true, 'delivered', false, 'cancelled', true, 'shop_new', true)))
on conflict (key) do nothing;

-- 2. Outbox ---------------------------------------------------------------------------------------------------------------
create table if not exists public.sms_outbox (
  id          bigint generated by default as identity primary key,
  phone       text not null,                    -- 01XXXXXXXXX (the function adds 88)
  body        text not null check (char_length(body) <= 480),
  kind        text not null,                    -- placed | confirmed | shipped | delivered | cancelled | shop_new | test
  order_id    bigint references public.orders (id) on delete set null,
  status      text not null default 'pending' check (status in ('pending', 'sent', 'failed', 'skipped')),
  attempts    integer not null default 0,
  error       text,
  provider_ref text,
  created_at  timestamptz not null default now(),
  sent_at     timestamptz
);
create index if not exists sms_outbox_pending on public.sms_outbox (created_at) where status = 'pending';
alter table public.sms_outbox enable row level security;
revoke all on public.sms_outbox from anon, authenticated;   -- only database functions and the server touch it

-- 3. Building and queueing messages --------------------------------------------------------------------------------------
create or replace function public.sms_phone(p text)
returns text language sql immutable set search_path = ''
as $$ select case when r ~ '^01[3-9][0-9]{8}$' then r end
        from (select right(regexp_replace(coalesce(p, ''), '[^0-9]', '', 'g'), 11) as r) x $$;

create or replace function public.sms_text(p_kind text, o public.orders, p_lang text)
returns text language plpgsql stable security definer set search_path = ''
as $$
declare
  shop text; tot text; trk text := '';
begin
  select left(coalesce(case when p_lang = 'bn' then nullif(sd.shop_name_bn, '') end, sd.shop_name, 'the shop'), 28)
    into shop from public.seller_details sd where sd.user_id = o.seller_id;
  shop := coalesce(shop, 'the shop');
  tot := trim(to_char(o.total, 'FM999999990'));
  if p_kind = 'shipped' and o.courier is not null and o.courier_tracking is not null then
    trk := case when p_lang = 'bn' then format(' (%s: %s)', initcap(o.courier), o.courier_tracking)
                else format(' via %s, tracking %s', initcap(o.courier), o.courier_tracking) end;
  end if;
  if p_lang = 'bn' then
    return case p_kind
      when 'placed'    then format('RGBKart: অর্ডার %s (%s) হয়েছে। মোট %s টাকা, ডেলিভারির সময় দেবেন। rgbkart.com/orders.html', o.order_no, shop, tot)
      when 'confirmed' then format('RGBKart: %s আপনার অর্ডার %s কনফার্ম করেছে।', shop, o.order_no)
      when 'shipped'   then format('RGBKart: অর্ডার %s পাঠানো হয়েছে%s। ডেলিভারির সময় %s টাকা দেবেন।', o.order_no, trk, tot)
      when 'delivered' then format('RGBKart: অর্ডার %s ডেলিভারি হয়েছে। ধন্যবাদ! রেটিং দিন: rgbkart.com/orders.html', o.order_no)
      when 'cancelled' then format('RGBKart: অর্ডার %s বাতিল হয়েছে। বিস্তারিত: rgbkart.com/orders.html', o.order_no)
      when 'shop_new'  then format('RGBKart: নতুন অর্ডার %s, %s টাকা (%s)। সেলার সেন্টারে কনফার্ম করুন।', o.order_no, tot, coalesce(o.district, ''))
    end;
  end if;
  return case p_kind
    when 'placed'    then format('RGBKart: Order %s placed with %s. Total Tk %s, pay on delivery. Track: rgbkart.com/orders.html', o.order_no, shop, tot)
    when 'confirmed' then format('RGBKart: %s confirmed your order %s. We will SMS you when it ships.', shop, o.order_no)
    when 'shipped'   then format('RGBKart: Order %s is on the way%s. Pay Tk %s on delivery.', o.order_no, trk, tot)
    when 'delivered' then format('RGBKart: Order %s delivered. Thank you! Rate it: rgbkart.com/orders.html', o.order_no)
    when 'cancelled' then format('RGBKart: Order %s was cancelled. Details: rgbkart.com/orders.html', o.order_no)
    when 'shop_new'  then format('RGBKart: New order %s, Tk %s from %s. Open Seller Center to confirm.', o.order_no, tot, coalesce(nullif(o.district, ''), 'a buyer'))
  end;
end; $$;
revoke execute on function public.sms_text(text, public.orders, text) from public, anon, authenticated;

