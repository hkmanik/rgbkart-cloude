-- Fraud & reports (plan 6.5).
-- 1. Anyone (also a guest, with the invisible guest sign-in) can report a product or a shop to RGBKart staff: reason + details.
--    Staff see the reports in Admin → Complaints, add a note and mark them reviewing / resolved / dismissed. The reporter gets an alert when it is closed.
-- 2. Risky Cash-on-Delivery buyers: sellers see, for each order, how this buyer did before on RGBKart (all shops together, counts only):
--    delivered orders, deliveries refused (a shop cancelled after shipping) and orders the buyer cancelled. Buyers are matched by account and by phone number.
-- Run once in Supabase → SQL Editor, AFTER 0029_reviews.sql. Safe to run again.

-- 1. Reports ---------------------------------------------------------------------------------------------------
create table if not exists public.reports (
  id           bigint generated by default as identity primary key,
  reporter_id  uuid not null default auth.uid() references auth.users (id) on delete cascade,
  product_id   bigint references public.products (id) on delete set null,
  seller_id    uuid references public.profiles (id) on delete set null,          -- the shop / seller the report is about
  reason       text not null check (reason in ('fake', 'scam', 'wrong_info', 'prohibited', 'offensive', 'spam', 'no_delivery', 'other')),
  details      text check (details is null or char_length(details) <= 1000),
  contact      text check (contact is null or char_length(contact) <= 80),       -- optional phone / email of the reporter
  status       text not null default 'open' check (status in ('open', 'reviewing', 'resolved', 'dismissed')),
  admin_note   text check (admin_note is null or char_length(admin_note) <= 1000),
  handled_by   uuid,
  handled_at   timestamptz,
  created_at   timestamptz not null default now()
);
create index if not exists reports_status on public.reports (status, created_at desc);
create index if not exists reports_seller on public.reports (seller_id);
create index if not exists reports_product on public.reports (product_id);

alter table public.reports enable row level security;
revoke all on public.reports from anon, authenticated;
grant select on public.reports to authenticated;          -- changes only through the functions below
drop policy if exists "Own reports and staff" on public.reports;
create policy "Own reports and staff" on public.reports for select to authenticated
  using (reporter_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));

create or replace function public.submit_report(p_product bigint, p_seller uuid, p_reason text, p_details text default null, p_contact text default null)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare sid uuid; d text; rid bigint;
begin
  if auth.uid() is null then raise exception 'Please sign in first'; end if;
  if p_reason is null or p_reason not in ('fake', 'scam', 'wrong_info', 'prohibited', 'offensive', 'spam', 'no_delivery', 'other') then
    raise exception 'Choose a reason';
  end if;
  if p_product is not null then
    select seller_id into sid from public.products where id = p_product;
    if sid is null then raise exception 'Product not found'; end if;
  else
    sid := p_seller;
    if sid is null or not exists (select 1 from public.seller_details where user_id = sid) then raise exception 'Shop not found'; end if;
  end if;
  if sid = auth.uid() then raise exception 'You cannot report your own listing'; end if;
  d := nullif(trim(regexp_replace(coalesce(p_details, ''), '\s+', ' ', 'g')), '');
  if char_length(d) > 1000 then raise exception 'Please keep the details under 1000 letters'; end if;
  if p_reason = 'other' and d is null then raise exception 'Please tell us what is wrong'; end if;
  if (select count(*) from public.reports where reporter_id = auth.uid() and created_at > now() - interval '1 day') >= 10 then
    raise exception 'You have sent many reports today. Please try again tomorrow.';
  end if;
  if exists (select 1 from public.reports where reporter_id = auth.uid() and status in ('open', 'reviewing')
             and coalesce(product_id, 0) = coalesce(p_product, 0) and seller_id = sid) then
    raise exception 'You have already reported this. Our team is checking it.';
  end if;
  insert into public.reports (reporter_id, product_id, seller_id, reason, details, contact)
  values (auth.uid(), p_product, sid, p_reason, d, left(nullif(trim(coalesce(p_contact, '')), ''), 80))
  returning id into rid;
  return rid;
end; $$;
revoke execute on function public.submit_report(bigint, uuid, text, text, text) from public, anon;
grant  execute on function public.submit_report(bigint, uuid, text, text, text) to authenticated;

create or replace function public.admin_update_report(p_report bigint, p_status text, p_note text default null)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if not public.has_staff_role(array['master_admin', 'co_admin', 'editor']) then raise exception 'Only RGBKart staff can do this'; end if;
  if p_status not in ('open', 'reviewing', 'resolved', 'dismissed') then raise exception 'Unknown status'; end if;
  update public.reports set status = p_status, admin_note = coalesce(nullif(trim(coalesce(p_note, '')), ''), admin_note),
         handled_by = auth.uid(), handled_at = now()
   where id = p_report;
  if not found then raise exception 'Report not found'; end if;
end; $$;
revoke execute on function public.admin_update_report(bigint, text, text) from public, anon;
grant  execute on function public.admin_update_report(bigint, text, text) to authenticated;

-- Alerts: staff hear about new reports; the reporter hears when it is closed
create or replace function public.alerts_reports()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare st record; what text;
begin
  what := coalesce((select title from public.products where id = new.product_id),
                   (select shop_name from public.seller_details where user_id = new.seller_id), 'a listing');
  if tg_op = 'INSERT' then
    for st in select distinct user_id from public.staff where staff_role in ('master_admin', 'co_admin', 'editor') loop
      perform public.notify(st.user_id, 'report_new', format('New complaint: %s', left(what, 90)),
        coalesce(new.details, 'Reason: ' || new.reason), 'admin.html#complaints', 'report:' || new.id);
    end loop;
  elsif new.status in ('resolved', 'dismissed') and old.status is distinct from new.status then
    perform public.notify(new.reporter_id, 'report_closed',
      case when new.status = 'resolved' then 'Thank you: we acted on your report' else 'We checked your report' end,
      coalesce(new.admin_note, case when new.status = 'resolved' then 'Our team has taken action. Thank you for helping keep RGBKart safe.'
                                    else 'We did not find a problem this time. Thank you for telling us.' end),
      null, 'report:' || new.id);
  end if;
  return null;
end; $$;
drop trigger if exists alerts_reports on public.reports;
create trigger alerts_reports after insert or update of status on public.reports for each row execute function public.alerts_reports();

-- 2. Buyer history for risky Cash-on-Delivery orders -------------------------------------------------------------
-- For each order the caller may see (its shop, or staff): how this buyer did on other orders, on all shops.
create or replace function public.order_buyer_history(p_orders bigint[])
returns table (order_id bigint, delivered integer, refused integer, buyer_cancelled integer, open_orders integer, level text)
language sql stable security definer set search_path = ''
as $$
  with mine as (
    select o.id, o.customer_id, right(regexp_replace(o.phone, '[^0-9]', '', 'g'), 10) as ph, o.created_at
    from public.orders o
    where o.id = any (p_orders)
      and (o.seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin', 'editor']))
  ), hist as (
    select m.id,
           count(*) filter (where x.status = 'delivered')::int as delivered,
           count(*) filter (where x.status = 'cancelled' and x.cancelled_by in ('seller', 'admin') and x.shipped_at is not null)::int as refused,
           count(*) filter (where x.status = 'cancelled' and x.cancelled_by = 'customer')::int as buyer_cancelled,
           count(*) filter (where x.status in ('pending', 'confirmed', 'packed', 'shipped'))::int as open_orders
    from mine m
    left join public.orders x on x.id <> m.id
      and (x.customer_id = m.customer_id or (length(m.ph) = 10 and right(regexp_replace(x.phone, '[^0-9]', '', 'g'), 10) = m.ph))
    group by m.id
  )
  select h.id, h.delivered, h.refused, h.buyer_cancelled, h.open_orders,
         case when h.refused >= 2 or (h.refused >= 1 and h.delivered = 0) or h.buyer_cancelled >= 3 then 'high'
              when h.refused = 1 or h.buyer_cancelled >= 2 or h.open_orders >= 4 then 'watch'
              when h.delivered >= 2 then 'trusted'
              when h.delivered = 0 and h.refused = 0 and h.buyer_cancelled = 0 then 'new'
              else 'ok' end
  from hist h
$$;
revoke execute on function public.order_buyer_history(bigint[]) from public, anon;
grant  execute on function public.order_buyer_history(bigint[]) to authenticated;

select to_regclass('public.reports') is not null as reports_ready,
       to_regprocedure('public.order_buyer_history(bigint[])') is not null as buyer_check_ready;
