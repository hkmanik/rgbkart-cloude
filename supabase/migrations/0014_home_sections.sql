insert into public.home_sections (title, subtitle, section_type, category_id, item_count, sort_order)
select 'Gaming & RGB Setup', 'Keyboards, mice, headsets and RGB lights', 'category', c.id, 12, 50
from public.categories c
where c.slug = 'gaming-and-rgb-setup'
  and not exists (select 1 from public.home_sections where section_type = 'category');

