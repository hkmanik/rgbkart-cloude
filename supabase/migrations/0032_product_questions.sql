-- Product questions & answers (plan 6.3).
-- Shoppers (also guests, with the invisible guest sign-in) ask a question on a product page; the seller answers it there or in
-- Seller Center → Questions, and the answer is shown to everyone. Staff can hide a question (Admin → Questions).
-- Contact rule: a one-time seller's FREE listing hides the phone number, so their answers may not contain a phone number,
-- email or link (otherwise the free listing would get the paid Featured contact for free).
-- Run once in Supabase → SQL Editor, AFTER 0031_saved_lists.sql. Safe to run again.

create table if not exists public.product_questions (
  id             bigint generated by default as identity primary key,
  product_id     bigint not null references public.products (id) on delete cascade,
  seller_id      uuid not null references public.profiles (id) on delete cascade,
  asker_id       uuid not null default auth.uid() references auth.users (id) on delete cascade,
  asker_name     text not null,                                              -- shown to everyone, e.g. "Karim A." or "Guest"
  question       text not null check (char_length(question) between 3 and 500),
  answer         text check (answer is null or char_length(answer) <= 1000),
  answered_at    timestamptz,
  is_hidden      boolean not null default false,
  hidden_reason  text,
  created_at     timestamptz not null default now()
);
create index if not exists product_questions_product on public.product_questions (product_id, created_at desc);
create index if not exists product_questions_seller on public.product_questions (seller_id, answered_at nulls first, created_at desc);
create index if not exists product_questions_asker on public.product_questions (asker_id);

alter table public.product_questions enable row level security;
revoke all on public.product_questions from anon, authenticated;
grant select on public.product_questions to authenticated;   -- changes only through the functions below
drop policy if exists "Own questions, seller and staff" on public.product_questions;
create policy "Own questions, seller and staff" on public.product_questions for select to authenticated
  using (asker_id = auth.uid() or seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));

-- What everyone sees: answered, not hidden (no user ids)
create or replace view public.public_questions as
  select q.id, q.product_id, q.asker_name, q.question, q.answer, q.answered_at, q.created_at
  from public.product_questions q
  where q.answer is not null and not q.is_hidden;
grant select on public.public_questions to anon, authenticated;

-- Ask -----------------------------------------------------------------------------------------------------------
create or replace function public.ask_question(p_product bigint, p_question text)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare p record; q text; nm text; anon boolean; rid bigint;
begin
  if auth.uid() is null then raise exception 'Please sign in first'; end if;
  select id, seller_id, status into p from public.products where id = p_product;
  if p.id is null or p.status <> 'approved' then raise exception 'Product not found'; end if;
  if p.seller_id = auth.uid() then raise exception 'You cannot ask a question about your own product'; end if;
  q := nullif(trim(regexp_replace(coalesce(p_question, ''), '\s+', ' ', 'g')), '');
  if q is null or char_length(q) < 3 then raise exception 'Please write your question'; end if;
  if char_length(q) > 500 then raise exception 'Please keep the question under 500 letters'; end if;
  if (select count(*) from public.product_questions where asker_id = auth.uid() and created_at > now() - interval '1 day') >= 10 then
    raise exception 'You have asked many questions today. Please try again tomorrow.';
  end if;
  if exists (select 1 from public.product_questions where asker_id = auth.uid() and product_id = p_product and lower(question) = lower(q)) then
    raise exception 'You have already asked this question';
  end if;
  anon := coalesce((select is_anonymous from auth.users where id = auth.uid()), false);
  nm := trim(coalesce(nullif(trim((select full_name from public.profiles where id = auth.uid())), ''), ''));
  nm := case when anon or nm = '' then 'Guest'
             when position(' ' in nm) > 0 then split_part(nm, ' ', 1) || ' ' || left(split_part(nm, ' ', array_length(regexp_split_to_array(nm, '\s+'), 1)), 1) || '.'
             else nm end;
  insert into public.product_questions (product_id, seller_id, asker_id, asker_name, question)
  values (p_product, p.seller_id, auth.uid(), left(nm, 40), q) returning id into rid;
  return rid;
end; $$;
revoke execute on function public.ask_question(bigint, text) from public, anon;
grant  execute on function public.ask_question(bigint, text) to authenticated;

-- Answer (the seller of the product, or staff). Empty answer removes it. ----------------------------------------
create or replace function public.answer_question(p_question bigint, p_answer text)
returns void language plpgsql security definer set search_path = ''
as $$
declare q public.product_questions; a text; free_listing boolean;
begin
  select * into q from public.product_questions where id = p_question;
  if q.id is null or (q.seller_id <> auth.uid() and not public.has_staff_role(array['master_admin', 'co_admin', 'editor'])) then
    raise exception 'Question not found';
  end if;
  a := nullif(trim(coalesce(p_answer, '')), '');
  if char_length(a) > 1000 then raise exception 'Please keep the answer under 1000 letters'; end if;
  -- one-time seller, not Featured: no phone numbers, emails or links in answers
  select exists (select 1 from public.products p join public.profiles pr on pr.id = p.seller_id
                 where p.id = q.product_id and pr.role = 'individual' and not coalesce(p.is_featured, false)) into free_listing;
  if a is not null and free_listing and not public.has_staff_role(array['master_admin', 'co_admin', 'editor'])
     and (regexp_replace(a, '[\s\-().]', '', 'g') ~ '(\+?88)?01[3-9][0-9]{8}' or a ~* '[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}' or a ~* '(https?://|www\.|wa\.me)') then
    raise exception 'Free listings cannot share a phone number, email or link in answers. Buyers can message you on RGBKart, or make the listing Featured to show your contact.';
  end if;
  update public.product_questions set answer = a, answered_at = case when a is null then null else now() end where id = q.id;
end; $$;
revoke execute on function public.answer_question(bigint, text) from public, anon;
grant  execute on function public.answer_question(bigint, text) to authenticated;

-- Staff hide / show ---------------------------------------------------------------------------------------------
create or replace function public.admin_hide_question(p_question bigint, p_hide boolean, p_reason text default null)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if not public.has_staff_role(array['master_admin', 'co_admin', 'editor']) then raise exception 'Only RGBKart staff can do this'; end if;
  update public.product_questions set is_hidden = coalesce(p_hide, false),
         hidden_reason = case when p_hide then nullif(trim(coalesce(p_reason, '')), '') end
   where id = p_question;
  if not found then raise exception 'Question not found'; end if;
end; $$;
revoke execute on function public.admin_hide_question(bigint, boolean, text) from public, anon;
grant  execute on function public.admin_hide_question(bigint, boolean, text) to authenticated;

-- Alerts: the seller hears about a new question, the asker hears about the answer -------------------------------
create or replace function public.alerts_questions()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare t text; indiv boolean;
begin
  t := coalesce((select title from public.products where id = new.product_id), 'your product');
  if tg_op = 'INSERT' then
    indiv := exists (select 1 from public.profiles where id = new.seller_id and role = 'individual');
    perform public.notify(new.seller_id, 'question_new', format('New question about %s', left(t, 90)), new.question,
      case when indiv then 'product.html?id=' || new.product_id || '#questions' else 'seller.html#questions' end, 'question:' || new.id);
  elsif new.answer is not null and old.answer is null then
    perform public.notify(new.asker_id, 'question_answered', 'The seller answered your question',
      left(new.answer, 500), 'product.html?id=' || new.product_id || '#questions', 'question:' || new.id);
  end if;
  return null;
end; $$;
drop trigger if exists alerts_questions on public.product_questions;
create trigger alerts_questions after insert or update of answer on public.product_questions for each row execute function public.alerts_questions();

select to_regclass('public.product_questions') is not null as questions_ready;
