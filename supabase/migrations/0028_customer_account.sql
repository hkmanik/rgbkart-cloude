-- Customer account (plan 3.1): saved delivery addresses (address book) for the My account page and checkout.
-- Each customer keeps up to 10 addresses; one is the default and is filled in at checkout automatically.
-- Run once in Supabase → SQL Editor, AFTER 0027_section_settings.sql. Safe to run again.

create table if not exists public.customer_addresses (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  label       text check (label is null or char_length(label) <= 30),                     -- e.g. Home, Office
  full_name   text not null check (char_length(trim(full_name)) between 2 and 80),
  phone       text check (phone is null or phone ~ '^(\+?880)?01[3-9][0-9]{8}$'),
  address     text not null check (char_length(trim(address)) between 5 and 300),
  district    text not null check (char_length(district) between 2 and 40),
  area        text check (area is null or char_length(area) <= 60),
  is_default  boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists customer_addresses_user on public.customer_addresses (user_id);
create unique index if not exists customer_addresses_one_default on public.customer_addresses (user_id) where is_default;

alter table public.customer_addresses enable row level security;
revoke all on public.customer_addresses from anon, authenticated;
grant select, insert, update, delete on public.customer_addresses to authenticated;
drop policy if exists "Own addresses" on public.customer_addresses;
create policy "Own addresses" on public.customer_addresses for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

-- Rules: at most 10; the first one becomes the default; choosing a new default clears the old one; deleting the default picks another.
create or replace function public.customer_addresses_rules()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.is_default then
      update public.customer_addresses set is_default = true
       where id = (select id from public.customer_addresses where user_id = old.user_id and id <> old.id order by updated_at desc limit 1);
    end if;
    return old;
  end if;
  new.user_id := coalesce(new.user_id, auth.uid());
  new.updated_at := now();
  new.full_name := trim(new.full_name); new.address := trim(new.address);
  new.label := nullif(trim(coalesce(new.label, '')), ''); new.area := nullif(trim(coalesce(new.area, '')), '');
  new.phone := nullif(regexp_replace(coalesce(new.phone, ''), '[^0-9+]', '', 'g'), '');
  if tg_op = 'INSERT' then
    if (select count(*) from public.customer_addresses where user_id = new.user_id) >= 10 then
      raise exception 'You can save up to 10 addresses. Delete one first.';
    end if;
    if not exists (select 1 from public.customer_addresses where user_id = new.user_id) then new.is_default := true; end if;
  end if;
  if new.is_default then
    update public.customer_addresses set is_default = false where user_id = new.user_id and is_default and id <> coalesce(new.id, -1);
  end if;
  return new;
end; $$;
drop trigger if exists customer_addresses_rules on public.customer_addresses;
create trigger customer_addresses_rules before insert or update on public.customer_addresses for each row execute function public.customer_addresses_rules();
drop trigger if exists customer_addresses_after_delete on public.customer_addresses;
create trigger customer_addresses_after_delete after delete on public.customer_addresses for each row execute function public.customer_addresses_rules();

-- Bring over the address customers typed when they signed up (only if they have none saved yet)
insert into public.customer_addresses (user_id, label, full_name, phone, address, district, is_default)
select c.user_id, 'Home', coalesce(nullif(trim(p.full_name), ''), 'Customer'),
       case when regexp_replace(coalesce(p.phone, ''), '[^0-9+]', '', 'g') ~ '^(\+?880)?01[3-9][0-9]{8}$' then regexp_replace(p.phone, '[^0-9+]', '', 'g') end,
       trim(c.address), coalesce(nullif(trim(c.city), ''), 'Dhaka'), true
from public.customer_details c join public.profiles p on p.id = c.user_id
where char_length(trim(coalesce(c.address, ''))) >= 5 and char_length(coalesce(nullif(trim(c.city), ''), 'Dhaka')) <= 40
  and not exists (select 1 from public.customer_addresses a where a.user_id = c.user_id);

select (select count(*) from public.customer_addresses) as saved_addresses;
