-- Reviews & ratings (plan 6.1).
-- Only customers whose order was DELIVERED can rate: the shop (1–5 stars, required) and each product in the order (optional).
-- Reviews can be written for 90 days after delivery and changed for 30 days after writing. The shop can reply once (and edit the reply).
-- Staff can hide a rude or fake review (it stays in the database, the stars stop counting).
-- Products and shops get rating_avg / rating_count, kept up to date automatically; nobody can type them in by hand.
-- Run once in Supabase → SQL Editor, AFTER 0028_customer_account.sql. Safe to run again.

-- 1. Table ---------------------------------------------------------------------------------------------------
create table if not exists public.reviews (
  id             bigint generated by default as identity primary key,
  order_id       bigint not null references public.orders (id) on delete cascade,
  product_id     bigint references public.products (id) on delete cascade,    -- empty = review of the shop
  seller_id      uuid not null references public.profiles (id) on delete cascade,
  user_id        uuid not null references auth.users (id) on delete cascade,
  rating         smallint not null check (rating between 1 and 5),
  comment        text check (comment is null or char_length(comment) <= 1000),
  reviewer_name  text not null,                                                -- shown to everyone, e.g. "Karim A."
  reply          text check (reply is null or char_length(reply) <= 1000),
  replied_at     timestamptz,
  is_hidden      boolean not null default false,
  hidden_reason  text,
  hidden_by      uuid,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create unique index if not exists reviews_one_per_item on public.reviews (order_id, coalesce(product_id, 0));
create index if not exists reviews_product on public.reviews (product_id, created_at desc) where product_id is not null;
create index if not exists reviews_seller on public.reviews (seller_id, created_at desc);
create index if not exists reviews_user on public.reviews (user_id);

alter table public.reviews enable row level security;
revoke all on public.reviews from anon, authenticated;
grant select on public.reviews to authenticated;          -- changes only through the functions below
drop policy if exists "Read own reviews" on public.reviews;
create policy "Read own reviews" on public.reviews for select to authenticated
  using (user_id = auth.uid() or seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));

-- What shoppers see (no customer ids, hidden reviews left out)
create or replace view public.public_reviews as
  select r.id, r.product_id, r.seller_id, r.rating, r.comment, r.reviewer_name, r.reply, r.replied_at, r.created_at,
         case when r.product_id is null then 'shop' else 'product' end as kind,
         (select string_agg(distinct oi.variant_label, ', ') from public.order_items oi
           where oi.order_id = r.order_id and oi.product_id = r.product_id and oi.variant_label is not null) as variant_label
  from public.reviews r
  where not r.is_hidden;
grant select on public.public_reviews to anon, authenticated;

-- 2. Star averages on products and shops ------------------------------------------------------------------
alter table public.products       add column if not exists rating_avg numeric(3, 2);
alter table public.products       add column if not exists rating_count integer not null default 0;
alter table public.seller_details add column if not exists rating_avg numeric(3, 2);
alter table public.seller_details add column if not exists rating_count integer not null default 0;
create index if not exists products_rating on public.products (rating_avg desc nulls last, rating_count desc);

-- Sellers can edit their own products / shop, so these columns are protected: only the review system may change them.
create or replace function public.ratings_guard()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if coalesce(current_setting('rgbkart.ratings', true), '') = 'on' then return new; end if;
  if tg_op = 'INSERT' then
    new.rating_avg := null; new.rating_count := 0;
  else
    new.rating_avg := old.rating_avg; new.rating_count := old.rating_count;
  end if;
  return new;
end; $$;
drop trigger if exists ratings_guard on public.products;
create trigger ratings_guard before insert or update on public.products for each row execute function public.ratings_guard();
drop trigger if exists ratings_guard on public.seller_details;
create trigger ratings_guard before insert or update on public.seller_details for each row execute function public.ratings_guard();

create or replace function public.refresh_ratings(p_product bigint, p_seller uuid)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  perform set_config('rgbkart.ratings', 'on', true);
  if p_product is not null then
    update public.products p set
      rating_avg   = (select round(avg(rating), 2) from public.reviews where product_id = p_product and not is_hidden),
      rating_count = (select count(*) from public.reviews where product_id = p_product and not is_hidden)
    where p.id = p_product;
  end if;
  if p_seller is not null then
    update public.seller_details s set
      rating_avg   = (select round(avg(rating), 2) from public.reviews where seller_id = p_seller and product_id is null and not is_hidden),
      rating_count = (select count(*) from public.reviews where seller_id = p_seller and product_id is null and not is_hidden)
    where s.user_id = p_seller;
  end if;
  perform set_config('rgbkart.ratings', 'off', true);
end; $$;
revoke execute on function public.refresh_ratings(bigint, uuid) from public, anon, authenticated;

create or replace function public.reviews_after_change()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare r public.reviews; stars text; what text;
begin
  r := case when tg_op = 'DELETE' then old else new end;
  perform public.refresh_ratings(r.product_id, case when r.product_id is null then r.seller_id end);
  if tg_op = 'UPDATE' and old.product_id is distinct from new.product_id then
    perform public.refresh_ratings(old.product_id, null);
  end if;

  -- Alerts: the shop hears about new reviews, the customer hears about the shop's reply
  if tg_op = 'INSERT' then
    stars := repeat('★', new.rating) || repeat('☆', 5 - new.rating);
    what := case when new.product_id is null then 'your shop'
                 else coalesce((select title from public.products where id = new.product_id), 'a product') end;
    perform public.notify(new.seller_id, 'review_new', format('New review %s for %s', stars, left(what, 80)),
      coalesce(nullif(new.comment, ''), 'No comment written.') || ' — ' || new.reviewer_name,
      'seller.html#reviews', 'review:' || new.id);
  elsif tg_op = 'UPDATE' and new.reply is not null and new.reply is distinct from old.reply and old.reply is null then
    perform public.notify(new.user_id, 'review_reply', 'The shop replied to your review',
      left(new.reply, 500),
      case when new.product_id is null then 'store.html?s=' || new.seller_id else 'product.html?id=' || new.product_id end,
      'review:' || new.id);
  end if;
  return null;
end; $$;
drop trigger if exists reviews_after_change on public.reviews;
create trigger reviews_after_change after insert or update or delete on public.reviews for each row execute function public.reviews_after_change();

-- 3. Customer writes / changes a review --------------------------------------------------------------------
-- p_product empty = rate the shop of that order.
create or replace function public.submit_review(p_order bigint, p_product bigint, p_rating integer, p_comment text default null)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare o public.orders; old_r public.reviews; nm text; rid bigint; c text;
begin
  if auth.uid() is null then raise exception 'Please sign in first'; end if;
  select * into o from public.orders where id = p_order;
  if o.id is null or o.customer_id <> auth.uid() then raise exception 'Order not found'; end if;
  if o.status <> 'delivered' then raise exception 'You can rate an order after it is delivered'; end if;
  if p_rating is null or p_rating not between 1 and 5 then raise exception 'Choose 1 to 5 stars'; end if;
  if p_product is not null and not exists (select 1 from public.order_items where order_id = p_order and product_id = p_product) then
    raise exception 'This product is not in that order';
  end if;
  c := nullif(trim(regexp_replace(coalesce(p_comment, ''), '\s+', ' ', 'g')), '');
  if char_length(c) > 1000 then raise exception 'Please keep the review under 1000 letters'; end if;

  select * into old_r from public.reviews where order_id = p_order and coalesce(product_id, 0) = coalesce(p_product, 0);
  if old_r.id is null then
    if coalesce(o.delivered_at, o.updated_at) < now() - interval '90 days' then
      raise exception 'Reviews can be written up to 90 days after delivery';
    end if;
    -- Name shown to everyone: first name + first letter of the last name
    nm := trim(coalesce(nullif(trim((select full_name from public.profiles where id = auth.uid())), ''), o.customer_name, 'Customer'));
    nm := case when position(' ' in nm) > 0
               then split_part(nm, ' ', 1) || ' ' || left(split_part(nm, ' ', array_length(regexp_split_to_array(nm, '\s+'), 1)), 1) || '.'
               else nm end;
    insert into public.reviews (order_id, product_id, seller_id, user_id, rating, comment, reviewer_name)
    values (p_order, p_product, o.seller_id, auth.uid(), p_rating, c, left(nm, 40))
    returning id into rid;
  else
    if old_r.created_at < now() - interval '30 days' then raise exception 'Reviews can be changed for 30 days after writing'; end if;
    update public.reviews set rating = p_rating, comment = c, updated_at = now() where id = old_r.id;
    rid := old_r.id;
  end if;
  return rid;
end; $$;
revoke execute on function public.submit_review(bigint, bigint, integer, text) from public, anon;
grant  execute on function public.submit_review(bigint, bigint, integer, text) to authenticated;

-- 4. Shop replies (empty text removes the reply) ------------------------------------------------------------
create or replace function public.seller_reply_review(p_review bigint, p_reply text)
returns void language plpgsql security definer set search_path = ''
as $$
declare r public.reviews; t text;
begin
  select * into r from public.reviews where id = p_review;
  if r.id is null or (r.seller_id <> auth.uid() and not public.has_staff_role(array['master_admin', 'co_admin'])) then
    raise exception 'Review not found';
  end if;
  t := nullif(trim(coalesce(p_reply, '')), '');
  if char_length(t) > 1000 then raise exception 'Please keep the reply under 1000 letters'; end if;
  update public.reviews set reply = t, replied_at = case when t is null then null else now() end where id = p_review;
end; $$;
revoke execute on function public.seller_reply_review(bigint, text) from public, anon;
grant  execute on function public.seller_reply_review(bigint, text) to authenticated;

-- 5. Staff hide / show a review --------------------------------------------------------------------------------
create or replace function public.admin_hide_review(p_review bigint, p_hide boolean, p_reason text default null)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if not public.has_staff_role(array['master_admin', 'co_admin', 'editor']) then raise exception 'Only RGBKart staff can do this'; end if;
  update public.reviews set is_hidden = coalesce(p_hide, false),
         hidden_reason = case when p_hide then nullif(trim(coalesce(p_reason, '')), '') end,
         hidden_by = case when p_hide then auth.uid() end
   where id = p_review;
  if not found then raise exception 'Review not found'; end if;
end; $$;
revoke execute on function public.admin_hide_review(bigint, boolean, text) from public, anon;
grant  execute on function public.admin_hide_review(bigint, boolean, text) to authenticated;

-- 6. Shop list and Top shops show the stars -----------------------------------------------------------------
create or replace view public.shops as
  select s.user_id, s.shop_name, s.shop_slug, s.tagline, s.shop_description, s.logo_path, s.banner_path, s.city,
         case when p.role = 'individual' then null else s.phone_public end as phone_public,
         case when p.role = 'individual' then null else s.whatsapp end as whatsapp,
         case when p.role = 'individual' then null else s.email_public end as email_public,
         s.facebook_url, s.instagram_url, s.youtube_url, s.tiktok_url, s.website_url,
         s.vacation_mode, s.vacation_message, s.created_at, s.area,
         s.allow_pickup, case when s.allow_pickup then s.business_address end as pickup_address,
         s.shop_name_bn, s.rating_avg, s.rating_count
  from public.seller_details s
  join public.profiles p on p.id = s.user_id
  where s.status = 'approved';
grant select on public.shops to anon, authenticated;

drop function if exists public.top_shops(integer);
create function public.top_shops(p_limit integer default 12)
returns table (user_id uuid, shop_name text, shop_name_bn text, shop_slug text, tagline text, logo_path text, banner_path text,
               city text, area text, featured_count integer, product_count integer, rating_avg numeric, rating_count integer)
language sql stable security definer set search_path = ''
as $$
  select s.user_id, s.shop_name, s.shop_name_bn, s.shop_slug, s.tagline, s.logo_path, s.banner_path, s.city, s.area,
         count(*) filter (where p.is_featured)::int, count(*)::int, s.rating_avg, s.rating_count
  from public.seller_details s
  join public.profiles pr on pr.id = s.user_id and pr.role = 'seller'      -- shops only, not one-time sellers
  join public.products p on p.seller_id = s.user_id and p.status = 'approved'
  where s.status = 'approved' and not coalesce(s.vacation_mode, false)
  group by s.user_id
  order by count(*) filter (where p.is_featured) desc, count(*) desc, max(p.published_at) desc nulls last
  limit greatest(1, least(coalesce(p_limit, 12), 48))
$$;
grant execute on function public.top_shops(integer) to anon, authenticated;

-- Bring the stars up to date (useful when this file is run again)
do $$
declare x record;
begin
  for x in select distinct product_id from public.reviews where product_id is not null loop perform public.refresh_ratings(x.product_id, null); end loop;
  for x in select distinct seller_id from public.reviews loop perform public.refresh_ratings(null, x.seller_id); end loop;
end $$;

select (select count(*) from public.reviews) as reviews, (select count(*) from public.products where rating_count > 0) as rated_products;
