-- Shop coupons (plan 3.6).
-- Each shop makes its own discount codes in Seller Center → Coupons: taka off or % off (with an optional most-you-can-save),
-- minimum order, start / end dates, how many times in total, and how many times per buyer. Discounts come off the shop's
-- items only (not delivery). Buyers type the code in the cart for that shop; place_order checks it again and records the use.
-- RGBKart takes no commission, so the shop gives the discount itself; RGBKart never holds money.
-- Orders get discount + coupon_code, and total = items + delivery − discount.
-- Run once in Supabase → SQL Editor, AFTER 0032_product_questions.sql. Safe to run again.

create table if not exists public.shop_coupons (
  id              bigint generated by default as identity primary key,
  seller_id       uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  code            text not null check (code ~ '^[A-Z0-9-]{3,20}$'),
  kind            text not null default 'amount' check (kind in ('amount', 'percent')),
  value           numeric(10, 2) not null check (value > 0),
  max_discount    numeric(10, 2) check (max_discount is null or max_discount > 0),     -- for % off: the most a buyer can save
  min_order       numeric(10, 2) not null default 0 check (min_order >= 0),             -- items total needed (before delivery)
  starts_at       timestamptz,
  ends_at         timestamptz,
  usage_limit     integer check (usage_limit is null or usage_limit > 0),               -- total uses, empty = no limit
  per_customer    integer not null default 1 check (per_customer between 1 and 100),
  used_count      integer not null default 0,
  is_active       boolean not null default true,
  note            text check (note is null or char_length(note) <= 120),
  created_at      timestamptz not null default now(),
  constraint shop_coupons_percent check (kind <> 'percent' or value <= 90),
  constraint shop_coupons_dates check (ends_at is null or starts_at is null or ends_at > starts_at),
  unique (seller_id, code)
);
create table if not exists public.coupon_uses (
  id           bigint generated by default as identity primary key,
  coupon_id    bigint not null references public.shop_coupons (id) on delete cascade,
  order_id     bigint not null references public.orders (id) on delete cascade,
  customer_id  uuid,
  phone        text,
  amount       numeric(10, 2) not null,
  created_at   timestamptz not null default now()
);
create index if not exists coupon_uses_coupon on public.coupon_uses (coupon_id);
alter table public.orders add column if not exists discount numeric(12, 2) not null default 0;
alter table public.orders add column if not exists coupon_code text;

alter table public.shop_coupons enable row level security;
alter table public.coupon_uses enable row level security;
revoke all on public.shop_coupons, public.coupon_uses from anon, authenticated;
grant select, insert, update, delete on public.shop_coupons to authenticated;
grant select on public.coupon_uses to authenticated;
drop policy if exists "Shop manages own coupons" on public.shop_coupons;
create policy "Shop manages own coupons" on public.shop_coupons for all to authenticated
  using (seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin']))
  with check (seller_id = auth.uid() and exists (select 1 from public.profiles where id = auth.uid() and role = 'seller'));
drop policy if exists "Shop sees own coupon uses" on public.coupon_uses;
create policy "Shop sees own coupon uses" on public.coupon_uses for select to authenticated
  using (exists (select 1 from public.shop_coupons c where c.id = coupon_id and (c.seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin']))));

-- Codes are stored in capitals; only place_order (runs as the database owner) may change used_count
create or replace function public.shop_coupons_before()
returns trigger language plpgsql set search_path = ''
as $$
begin
  new.code := upper(regexp_replace(coalesce(new.code, ''), '\s', '', 'g'));
  new.note := nullif(trim(coalesce(new.note, '')), '');
  if tg_op = 'INSERT' then new.used_count := 0;
  else
    new.seller_id := old.seller_id;
    if new.used_count is distinct from old.used_count and current_user not in ('postgres', 'supabase_admin') then new.used_count := old.used_count; end if;
  end if;
  return new;
end; $$;
drop trigger if exists shop_coupons_before on public.shop_coupons;
create trigger shop_coupons_before before insert or update on public.shop_coupons for each row execute function public.shop_coupons_before();

-- The discount a coupon gives on an items total, or a clear message why it can't be used.
create or replace function public.coupon_discount(cp public.shop_coupons, p_sub numeric, p_user uuid, p_phone text)
returns numeric language plpgsql stable security definer set search_path = ''
as $$
declare d numeric; used int; ph text := right(regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g'), 10);
begin
  if cp.id is null or not cp.is_active then raise exception 'This coupon code is not valid for this shop'; end if;
  if cp.starts_at is not null and cp.starts_at > now() then raise exception 'This coupon can be used from %', to_char(cp.starts_at at time zone 'Asia/Dhaka', 'DD Mon YYYY'); end if;
  if cp.ends_at is not null and cp.ends_at < now() then raise exception 'This coupon has expired'; end if;
  if cp.usage_limit is not null and cp.used_count >= cp.usage_limit then raise exception 'This coupon has been fully used'; end if;
  if p_sub < cp.min_order then raise exception 'This coupon needs an order of at least ৳% from this shop', to_char(cp.min_order, 'FM99,99,99,990'); end if;
  select count(*) into used from public.coupon_uses u join public.orders o on o.id = u.order_id
   where u.coupon_id = cp.id and o.status <> 'cancelled'
     and (u.customer_id = p_user or (length(ph) = 10 and right(regexp_replace(coalesce(u.phone, ''), '[^0-9]', '', 'g'), 10) = ph));
  if used >= cp.per_customer then raise exception 'You have already used this coupon'; end if;
  d := case when cp.kind = 'percent' then round(p_sub * cp.value / 100) else cp.value end;
  if cp.max_discount is not null then d := least(d, cp.max_discount); end if;
  return least(d, p_sub);
end; $$;
revoke execute on function public.coupon_discount(public.shop_coupons, numeric, uuid, text) from public, anon, authenticated;

-- A cancelled order gives its coupon use back
create or replace function public.coupon_on_cancel()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if new.status = 'cancelled' and old.status <> 'cancelled' and new.discount > 0 then
    update public.shop_coupons c set used_count = greatest(c.used_count - 1, 0)
     where c.id in (select u.coupon_id from public.coupon_uses u where u.order_id = new.id);
  end if;
  return null;
end; $$;
drop trigger if exists coupon_on_cancel on public.orders;
create trigger coupon_on_cancel after update of status on public.orders for each row execute function public.coupon_on_cancel();

-- Cart page: check a code for a shop and items total (the order checks again)
create or replace function public.check_coupon(p_seller uuid, p_code text, p_subtotal numeric)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare cp public.shop_coupons; d numeric; cc text := upper(regexp_replace(coalesce(p_code, ''), '\s', '', 'g'));
begin
  if cc = '' then raise exception 'Type a coupon code'; end if;
  select * into cp from public.shop_coupons where seller_id = p_seller and code = cc;
  d := public.coupon_discount(cp, coalesce(p_subtotal, 0), auth.uid(), (select phone from public.profiles where id = auth.uid()));
  return jsonb_build_object('code', cp.code, 'discount', d, 'kind', cp.kind, 'value', cp.value, 'min_order', cp.min_order);
end; $$;
revoke execute on function public.check_coupon(uuid, text, numeric) from public;
grant  execute on function public.check_coupon(uuid, text, numeric) to anon, authenticated;


-- Place order with coupons: same as 0024 plus the marked coupon lines
drop function if exists public.place_order(jsonb, jsonb, jsonb);
create or replace function public.place_order(p_items jsonb, p_ship jsonb, p_customer jsonb, p_coupons jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare
  uid uuid := auth.uid(); it jsonb; pr record; va record; vid bigint; unit numeric; qty int; lbl text; img text;
  ph text; nm text; addr text; dist text; sel uuid; m text; sm record; shop record; fee numeric; sub numeric;
  oid bigint; ono text; result jsonb := '[]'::jsonb; sellers uuid[]; nitems int := 0; tday text;
  cc text; cp public.shop_coupons; disc numeric;
begin
  if uid is null then raise exception 'Please reload the page and try again'; end if;
  nm := trim(coalesce(p_customer->>'name', '')); addr := trim(coalesce(p_customer->>'address', '')); dist := trim(coalesce(p_customer->>'district', ''));
  ph := regexp_replace(coalesce(p_customer->>'phone', ''), '[^0-9+]', '', 'g');
  if char_length(nm) < 2 then raise exception 'Enter your name'; end if;
  if ph !~ '^(\+?880)?01[3-9][0-9]{8}$' then raise exception 'Enter a valid mobile number, like 01711000000'; end if;
  if char_length(addr) < 5 then raise exception 'Enter your full delivery address (house, road, area)'; end if;
  if dist = '' then raise exception 'Choose your district'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Your cart is empty'; end if;
  if jsonb_array_length(p_items) > 30 then raise exception 'Too many items in one order (30 at most)'; end if;
  if (select count(*) from public.orders where customer_id = uid and created_at > now() - interval '1 day') >= 20 then
    raise exception 'You have placed many orders today. Please contact us if you need more.';
  end if;

  -- work out each line, grouped by shop
  create temp table if not exists _lines (seller_id uuid, product_id bigint, variation_id bigint, title text, label text, img text, unit numeric, qty int, manage boolean, free_del boolean, ships_to text) on commit drop;
  delete from _lines;
  for it in select * from jsonb_array_elements(p_items) loop
    qty := coalesce((it->>'qty')::int, 0);
    if qty < 1 or qty > 99 then raise exception 'Choose a quantity from 1 to 99'; end if;
    select p.*, sd.vacation_mode into pr from public.products p join public.seller_details sd on sd.user_id = p.seller_id and sd.status = 'approved'
     where p.id = (it->>'product_id')::bigint for update of p;
    if pr.id is null or pr.status <> 'approved' then raise exception 'An item in your cart is no longer available. Please remove it.'; end if;
    if pr.contact_only then raise exception '"%" can''t be ordered online. Contact the seller instead.', pr.title; end if;
    if pr.is_downloadable then raise exception '"%" is a digital product and can''t be ordered yet.', pr.title; end if;
    if not pr.cod_allowed then raise exception '"%" can''t be paid by Cash on Delivery.', pr.title; end if;
    if pr.vacation_mode then raise exception 'The shop selling "%" is on holiday and not taking orders.', pr.title; end if;
    if pr.seller_id = uid then raise exception 'You can''t order your own product'; end if;
    if pr.sold_individually then qty := 1; end if;
    lbl := null; vid := null; img := (select storage_path from public.product_images where product_id = pr.id order by sort_order limit 1);
    if pr.product_type = 'variable' then
      select v.* into va from public.product_variations v where v.id = (it->>'variation_id')::bigint and v.product_id = pr.id and v.is_active for update;
      if va.id is null then raise exception 'Choose an option for "%"', pr.title; end if;
      unit := coalesce(va.sale_price, va.price); vid := va.id;
      if va.stock < qty and pr.backorders = 'no' then raise exception 'Only % left of "%"', va.stock, pr.title; end if;
      select string_agg(o.value || coalesce(' ' || a.unit, ''), ' / ' order by a.name) into lbl
        from public.product_variation_options vo join public.attribute_options o on o.id = vo.option_id join public.attributes a on a.id = vo.attribute_id
       where vo.variation_id = va.id;
      if va.image_id is not null then img := coalesce((select storage_path from public.product_images where id = va.image_id), img); end if;
      update public.product_variations set stock = greatest(stock - qty, 0) where id = va.id;
    else
      unit := case when pr.sale_price is not null and (pr.sale_starts_at is null or pr.sale_starts_at <= now())
                         and (pr.sale_ends_at is null or pr.sale_ends_at >= now()) then pr.sale_price else pr.price end;
      -- bulk price: the lowest price for the quantity bought (set by the seller under Bulk prices)
      unit := least(unit, coalesce((select min(t.unit_price) from public.product_price_tiers t where t.product_id = pr.id and t.min_qty <= qty), unit));
      if pr.manage_stock and pr.stock < qty and pr.backorders = 'no' then
        if pr.stock = 0 then raise exception '"%" is out of stock', pr.title; end if;
        raise exception 'Only % left of "%"', pr.stock, pr.title;
      end if;
      if not pr.manage_stock and pr.stock_status = 'out_of_stock' then raise exception '"%" is out of stock', pr.title; end if;
      if pr.manage_stock then update public.products set stock = greatest(stock - qty, 0) where id = pr.id; end if;
    end if;
    if unit is null or unit <= 0 then raise exception '"%" has no price yet', pr.title; end if;
    insert into _lines values (pr.seller_id, pr.id, vid, pr.title, lbl, img, unit, qty, pr.manage_stock, pr.free_delivery, pr.ships_to);
    nitems := nitems + 1;
  end loop;

  -- one order per shop
  tday := to_char(now() at time zone 'Asia/Dhaka', 'YYMMDD');
  sellers := array(select distinct l.seller_id from _lines l);
  foreach sel in array sellers loop
    select * into shop from public.seller_details where user_id = sel;
    m := coalesce(p_ship->>(sel::text), 'negotiated');
    select * into sm from public.shipping_methods where id = m and is_active;
    if sm.id is null then raise exception 'Choose a delivery option for %', shop.shop_name; end if;
    if m = 'pickup' and not shop.allow_pickup then raise exception '% doesn''t offer store pickup', shop.shop_name; end if;
    if m = 'dhaka' and exists (select 1 from _lines l where l.seller_id = sel and l.ships_to = 'outside_dhaka') then raise exception 'Some items from % don''t deliver inside Dhaka', shop.shop_name; end if;
    if m = 'outside' and exists (select 1 from _lines l where l.seller_id = sel and l.ships_to = 'inside_dhaka') then raise exception 'Some items from % only deliver inside Dhaka', shop.shop_name; end if;
    sub := (select sum(l.unit * l.qty) from _lines l where l.seller_id = sel);
    fee := case when m in ('dhaka', 'outside') and not exists (select 1 from _lines l where l.seller_id = sel and not l.free_del) then 0
                when m in ('dhaka', 'outside') then sm.fee else 0 end;
    -- shop coupon (0033): checked again here, whatever the cart page showed
    disc := 0; cp := null;
    cc := upper(regexp_replace(coalesce(p_coupons->>(sel::text), ''), '\s', '', 'g'));
    if cc <> '' then
      select * into cp from public.shop_coupons c where c.seller_id = sel and c.code = cc for update;
      disc := public.coupon_discount(cp, sub, uid, ph);   -- raises a clear message if the code can't be used
    end if;
    loop
      ono := 'RGB-' || tday || '-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 5));
      exit when not exists (select 1 from public.orders where order_no = ono);
    end loop;
    insert into public.orders (order_no, customer_id, seller_id, customer_name, phone, email, address, district, area, note, ship_method, ship_fee, subtotal, total, discount, coupon_code)
    values (ono, uid, sel, left(nm, 80), ph, nullif(lower(trim(coalesce(p_customer->>'email', ''))), ''), left(addr, 300), left(dist, 40),
            nullif(left(trim(coalesce(p_customer->>'area', '')), 60), ''), nullif(left(trim(coalesce(p_customer->>'note', '')), 500), ''), m, fee, sub, sub + fee - disc,
            disc, case when disc > 0 then cp.code end)
    returning id into oid;
    if disc > 0 then
      insert into public.coupon_uses (coupon_id, order_id, customer_id, phone, amount) values (cp.id, oid, uid, ph, disc);
      update public.shop_coupons set used_count = used_count + 1 where id = cp.id;
    end if;
    insert into public.order_items (order_id, product_id, variation_id, title, variant_label, image_path, unit_price, qty, line_total)
    select oid, l.product_id, l.variation_id, l.title, l.label, l.img, l.unit, l.qty, l.unit * l.qty from _lines l where l.seller_id = sel;
    result := result || jsonb_build_object('order_no', ono, 'shop', shop.shop_name, 'phone', case when shop.phone_public is not null then shop.phone_public end, 'total', sub + fee - disc, 'discount', disc, 'ship', sm.name);
  end loop;

  -- remember the address on the customer's profile for next time
  insert into public.profiles (id) values (uid) on conflict (id) do nothing;
  update public.profiles set full_name = coalesce(nullif(full_name, ''), left(nm, 80)), phone = coalesce(nullif(phone, ''), ph) where id = uid;
  return result;
end; $$;

revoke execute on function public.place_order(jsonb, jsonb, jsonb, jsonb) from public, anon;
grant  execute on function public.place_order(jsonb, jsonb, jsonb, jsonb) to authenticated;

select to_regclass('public.shop_coupons') is not null as coupons_ready,
       to_regprocedure('public.place_order(jsonb,jsonb,jsonb,jsonb)') is not null as checkout_ready;
