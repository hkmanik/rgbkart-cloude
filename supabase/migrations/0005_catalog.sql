-- Catalog: categories, sub-categories and attributes.
-- Run once in Supabase → SQL Editor, AFTER setup.sql, profiles.sql and admin.sql.
-- Safe to run again.
--
-- Who can change the catalog: Master Admin and Co-admin.
-- Everyone (shoppers, sellers, Editors) can read it; shoppers see only categories that are switched on.

-- 1. Categories (one table; sub-categories point to their parent) ---------

create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  parent_id   bigint references public.categories (id) on delete restrict,
  name        text not null check (char_length(trim(name)) between 1 and 80),
  slug        text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  icon        text,                       -- an emoji (📱) or an image URL
  description text,
  sort_order  integer not null default 0,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists categories_parent_idx on public.categories (parent_id, sort_order);

-- A category can't be moved inside itself or one of its own sub-categories.
create or replace function public.categories_check_parent()
returns trigger language plpgsql set search_path = ''
as $$
declare p bigint := new.parent_id;
begin
  new.updated_at := now();
  while p is not null loop
    if p = new.id then raise exception 'A category can''t be placed inside itself or one of its sub-categories'; end if;
    select parent_id into p from public.categories where id = p;
  end loop;
  return new;
end; $$;

drop trigger if exists categories_check_parent on public.categories;
create trigger categories_check_parent before insert or update on public.categories
  for each row execute function public.categories_check_parent();

-- 2. Attributes (Colour, Size, RAM …) and their choices ------------------

create table if not exists public.attributes (
  id             bigint generated by default as identity primary key,
  name           text not null unique check (char_length(trim(name)) between 1 and 60),
  input_type     text not null default 'select'
                 check (input_type in ('text', 'number', 'select', 'multiselect', 'color', 'boolean')),
  unit           text,                    -- e.g. GB, inch, kg
  is_filterable  boolean not null default true,   -- shoppers can filter by it
  created_at     timestamptz not null default now()
);

create table if not exists public.attribute_options (
  id            bigint generated by default as identity primary key,
  attribute_id  bigint not null references public.attributes (id) on delete cascade,
  value         text not null check (char_length(trim(value)) between 1 and 60),
  color_hex     text check (color_hex is null or color_hex ~ '^#[0-9A-Fa-f]{6}$'),
  sort_order    integer not null default 0,
  unique (attribute_id, value)
);
create index if not exists attribute_options_attr_idx on public.attribute_options (attribute_id, sort_order);

-- Which attributes a category asks for. Sub-categories also get their parents' attributes.
create table if not exists public.category_attributes (
  category_id   bigint not null references public.categories (id) on delete cascade,
  attribute_id  bigint not null references public.attributes (id) on delete cascade,
  is_required   boolean not null default false,
  sort_order    integer not null default 0,
  primary key (category_id, attribute_id)
);

-- 3. Security ------------------------------------------------------------

alter table public.categories          enable row level security;
alter table public.attributes          enable row level security;
alter table public.attribute_options   enable row level security;
alter table public.category_attributes enable row level security;

grant select on public.categories, public.attributes, public.attribute_options, public.category_attributes to anon, authenticated;
revoke insert, update, delete on public.categories, public.attributes, public.attribute_options, public.category_attributes from anon;
grant  insert, update, delete on public.categories, public.attributes, public.attribute_options, public.category_attributes to authenticated;

do $$
declare t text;
begin
  foreach t in array array['categories', 'attributes', 'attribute_options', 'category_attributes'] loop
    execute format('drop policy if exists "Catalog managers write" on public.%I', t);
    execute format($p$create policy "Catalog managers write" on public.%I for all to authenticated
                     using (public.has_staff_role(array['master_admin','co_admin']))
                     with check (public.has_staff_role(array['master_admin','co_admin']))$p$, t);
  end loop;
end $$;

drop policy if exists "Anyone reads active categories" on public.categories;
create policy "Anyone reads active categories" on public.categories for select to anon, authenticated
  using (is_active or public.has_staff_role(array['master_admin','co_admin','editor']));

drop policy if exists "Anyone reads attributes" on public.attributes;
create policy "Anyone reads attributes" on public.attributes for select to anon, authenticated using (true);

drop policy if exists "Anyone reads attribute options" on public.attribute_options;
create policy "Anyone reads attribute options" on public.attribute_options for select to anon, authenticated using (true);

drop policy if exists "Anyone reads category attributes" on public.category_attributes;
create policy "Anyone reads category attributes" on public.category_attributes for select to anon, authenticated using (true);

-- has_staff_role must be callable by visitors who aren't signed in, because the policies above use it.
grant execute on function public.has_staff_role(text[]) to anon;
