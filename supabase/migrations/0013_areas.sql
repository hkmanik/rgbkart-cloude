-- Areas (thana / neighbourhood) for each district, used by the Sell page.
-- Run once in Supabase → SQL Editor, AFTER quick_sell.sql. Safe to run again.
-- Starts with common areas of Dhaka, Chattogram, Gazipur, Narayanganj and Sylhet, plus "<District> Sadar"
-- for every district. When a seller types a new area, it is added here and shows in the list next time.
-- To remove a wrong or rude area: Supabase → Table Editor → areas → delete the row.

create table if not exists public.areas (
  id          bigint generated by default as identity primary key,
  district    text not null,
  name        text not null check (char_length(name) between 2 and 40),
  added_by    uuid references auth.users (id) on delete set null,
  created_at  timestamptz not null default now()
);
create unique index if not exists areas_district_name_key on public.areas (district, lower(name));

alter table public.areas enable row level security;
revoke all on public.areas from anon, authenticated;
grant select on public.areas to anon, authenticated;
drop policy if exists "Anyone reads areas" on public.areas;
create policy "Anyone reads areas" on public.areas for select to anon, authenticated using (true);

