-- Products, part 2 (plan 1.5 + 1.6): WooCommerce-style product features.
-- Run once in Supabase → SQL Editor, AFTER products.sql. Safe to run again.
--
-- Adds: listing type (New / Pre-owned / Free), sale price with dates, stock management,
-- variations (e.g. Colour × Storage, each with its own price, stock and photo), shipping details,
-- short description, tags, video, linked products (upsell / cross-sell), purchase note,
-- return policy, and Featured listing requests (paid later, plan 5.4–5.7).

-- 1. New product columns --------------------------------------------------

alter table public.products
  add column if not exists listing_type        text not null default 'new',
  add column if not exists product_type        text not null default 'simple',
  add column if not exists short_description   text,
  add column if not exists tags                text[] not null default '{}',
  add column if not exists video_url           text,
  -- pricing
  add column if not exists sale_price          numeric(12, 2),
  add column if not exists sale_starts_at      timestamptz,
  add column if not exists sale_ends_at        timestamptz,
  -- inventory
  add column if not exists manage_stock        boolean not null default true,
  add column if not exists stock_status        text not null default 'in_stock',
  add column if not exists low_stock_threshold integer,
  add column if not exists backorders          text not null default 'no',
  add column if not exists sold_individually   boolean not null default false,
  -- shipping
  add column if not exists weight_kg           numeric(8, 3),
  add column if not exists length_cm           numeric(8, 1),
  add column if not exists width_cm            numeric(8, 1),
  add column if not exists height_cm           numeric(8, 1),
  add column if not exists shipping_class      text not null default 'standard',
  add column if not exists delivery_time       text not null default '1_2_days',
  add column if not exists ships_to            text not null default 'all_bangladesh',
  add column if not exists free_delivery       boolean not null default false,
  -- after-sale
  add column if not exists purchase_note       text,
  add column if not exists return_policy       text not null default '7_days';

-- The old "was price" is replaced by sale price (regular price = price).
alter table public.products drop column if exists compare_at_price;

-- Rules (dropped and re-added so this file can run again)
alter table public.products drop constraint if exists products_price_check;
alter table public.products drop constraint if exists products_rules;
alter table public.products add constraint products_rules check (
      listing_type   in ('new', 'pre_owned', 'free')
  and product_type   in ('simple', 'variable')
  and ((listing_type = 'free' and price = 0) or (listing_type <> 'free' and price > 0))
  and (sale_price is null or (sale_price > 0 and sale_price < price))
  and (sale_ends_at is null or sale_starts_at is null or sale_ends_at > sale_starts_at)
  and stock_status   in ('in_stock', 'out_of_stock', 'on_backorder')
  and backorders     in ('no', 'notify', 'yes')
  and (low_stock_threshold is null or low_stock_threshold >= 0)
  and (weight_kg is null or weight_kg > 0)
  and (length_cm is null or length_cm > 0) and (width_cm is null or width_cm > 0) and (height_cm is null or height_cm > 0)
  and shipping_class in ('standard', 'small', 'large', 'heavy', 'fragile')
  and delivery_time  in ('same_day', '1_2_days', '3_5_days', '6_10_days', 'pre_order')
  and ships_to       in ('all_bangladesh', 'inside_dhaka', 'outside_dhaka')
  and return_policy  in ('no_returns', '3_days', '7_days', '15_days', '30_days')
  and coalesce(array_length(tags, 1), 0) <= 20
  and (video_url is null or video_url ~* '^https?://')
  and (short_description is null or char_length(short_description) <= 600)
  and (purchase_note is null or char_length(purchase_note) <= 1000)
);
create index if not exists products_tags_idx on public.products using gin (tags);

-- 2. Variations --------------------------------------------------------

create table if not exists public.product_variations (
  id           bigint generated by default as identity primary key,
  product_id   bigint not null references public.products (id) on delete cascade,
  options_key  text not null,           -- sorted option ids, e.g. "12-87"; one row per combination
  sku          text check (sku is null or char_length(sku) <= 60),
  price        numeric(12, 2) not null check (price >= 0),
  sale_price   numeric(12, 2),
  stock        integer not null default 0 check (stock >= 0),
  image_id     bigint references public.product_images (id) on delete set null,
  is_active    boolean not null default true,
  sort_order   integer not null default 0,
  unique (product_id, options_key),
  check (sale_price is null or (sale_price > 0 and sale_price < price))
);
create index if not exists product_variations_product_idx on public.product_variations (product_id, sort_order);

create table if not exists public.product_variation_options (
  variation_id  bigint not null references public.product_variations (id) on delete cascade,
  attribute_id  bigint not null references public.attributes (id) on delete cascade,
  option_id     bigint not null references public.attribute_options (id) on delete cascade,
  primary key (variation_id, attribute_id)
);

create or replace function public.pvo_check()
returns trigger language plpgsql set search_path = ''
as $$
declare cat bigint; t text;
begin
  select p.category_id into cat from public.product_variations v join public.products p on p.id = v.product_id where v.id = new.variation_id;
  if not exists (select 1 from public.category_effective_attributes(cat) e where e.attribute_id = new.attribute_id) then
    raise exception 'This attribute doesn''t apply to the product''s category';
  end if;
  select input_type into t from public.attributes where id = new.attribute_id;
  if t not in ('select', 'color') then raise exception 'Only single-choice and colour attributes can make variations'; end if;
  if not exists (select 1 from public.attribute_options o where o.id = new.option_id and o.attribute_id = new.attribute_id) then
    raise exception 'That option doesn''t belong to this attribute';
  end if;
  return new;
end; $$;

drop trigger if exists pvo_check on public.product_variation_options;
create trigger pvo_check before insert or update on public.product_variation_options
  for each row execute function public.pvo_check();

-- A variation photo must be one of the product's own photos.
create or replace function public.pv_check()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if new.image_id is not null and not exists (select 1 from public.product_images i where i.id = new.image_id and i.product_id = new.product_id) then
    raise exception 'Pick a photo of this product';
  end if;
  return new;
end; $$;

drop trigger if exists pv_check on public.product_variations;
create trigger pv_check before insert or update on public.product_variations
  for each row execute function public.pv_check();

-- 3. Linked products (upsell = "you may also like", cross-sell = "frequently bought together") --

create table if not exists public.product_links (
  product_id         bigint not null references public.products (id) on delete cascade,
  linked_product_id  bigint not null references public.products (id) on delete cascade,
  kind               text not null check (kind in ('upsell', 'cross_sell')),
  sort_order         integer not null default 0,
  primary key (product_id, linked_product_id, kind),
  check (product_id <> linked_product_id)
);

-- 4. Featured listing requests (payment is added in plan 5.4–5.7) ---------

create table if not exists public.featured_requests (
  id           bigint generated by default as identity primary key,
  product_id   bigint not null references public.products (id) on delete cascade,
  seller_id    uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  placement    text not null check (placement in ('home', 'category')),
  days         integer not null check (days in (3, 7, 15, 30)),
  status       text not null default 'awaiting_payment'
               check (status in ('awaiting_payment', 'payment_submitted', 'active', 'expired', 'cancelled', 'rejected')),
  starts_at    timestamptz,
  ends_at      timestamptz,
  created_at   timestamptz not null default now()
);
create unique index if not exists featured_one_open on public.featured_requests (product_id)
  where status in ('awaiting_payment', 'payment_submitted', 'active');

-- 5. Automatic rules (updated) --------------------------------------------

create or replace function public.products_before_write()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare base text;
begin
  if tg_op = 'INSERT' then
    base := trim(both '-' from regexp_replace(lower(new.title), '[^a-z0-9]+', '-', 'g'));
    new.slug := left(coalesce(nullif(base, ''), 'product'), 80) || '-' || new.id;
    new.created_at := now();
  else
    new.slug := old.slug;
  end if;
  new.updated_at := now();
  new.tags := coalesce((select array_agg(distinct lower(trim(t))) from unnest(new.tags) t where trim(t) <> ''), '{}');

  if tg_op = 'UPDATE' and old.status = 'approved'
     and not public.has_staff_role(array['master_admin', 'co_admin', 'editor'])
     and (new.title is distinct from old.title
          or new.description is distinct from old.description
          or new.short_description is distinct from old.short_description
          or new.category_id is distinct from old.category_id
          or new.listing_type is distinct from old.listing_type) then
    new.status := 'pending';
  end if;
  return new;
end; $$;

-- Seller sends a product for review (now also checks variations).
create or replace function public.submit_product(p_product bigint)
returns text language plpgsql security definer set search_path = ''
as $$
declare p record; missing text;
begin
  select * into p from public.products where id = p_product and seller_id = auth.uid();
  if p.id is null then raise exception 'Product not found'; end if;
  if not public.is_approved_seller() then raise exception 'Your shop must be approved before you can list products'; end if;
  if p.status not in ('draft', 'rejected', 'archived') then raise exception 'This product is already %', p.status; end if;
  if not exists (select 1 from public.product_images where product_id = p.id) then
    raise exception 'Add at least one photo';
  end if;
  if p.product_type = 'variable' then
    if not exists (select 1 from public.product_variations where product_id = p.id and is_active) then
      raise exception 'Add at least one variation, or switch to a simple product';
    end if;
    if p.listing_type <> 'free' and exists (select 1 from public.product_variations where product_id = p.id and is_active and price <= 0) then
      raise exception 'Every active variation needs a price';
    end if;
  end if;
  select string_agg(a.name, ', ' order by a.name) into missing
    from public.category_effective_attributes(p.category_id) e
    join public.attributes a on a.id = e.attribute_id
   where e.is_required
     and not exists (select 1 from public.product_attribute_values v where v.product_id = p.id and v.attribute_id = e.attribute_id)
     and not exists (select 1 from public.product_variations pv join public.product_variation_options o on o.variation_id = pv.id
                     where pv.product_id = p.id and pv.is_active and o.attribute_id = e.attribute_id);
  if missing is not null then raise exception 'Fill in the required details: %', missing; end if;

  update public.products set status = 'pending', review_note = null where id = p.id;
  return 'pending';
end; $$;

-- 6. Security ----------------------------------------------------------------

grant insert (category_id, title, description, price, stock, sku,
              listing_type, product_type, short_description, tags, video_url,
              sale_price, sale_starts_at, sale_ends_at, manage_stock, stock_status, low_stock_threshold, backorders, sold_individually,
              weight_kg, length_cm, width_cm, height_cm, shipping_class, delivery_time, ships_to, free_delivery,
              purchase_note, return_policy) on public.products to authenticated;
grant update (category_id, title, description, price, stock, sku,
              listing_type, product_type, short_description, tags, video_url,
              sale_price, sale_starts_at, sale_ends_at, manage_stock, stock_status, low_stock_threshold, backorders, sold_individually,
              weight_kg, length_cm, width_cm, height_cm, shipping_class, delivery_time, ships_to, free_delivery,
              purchase_note, return_policy) on public.products to authenticated;

alter table public.product_variations        enable row level security;
alter table public.product_variation_options enable row level security;
alter table public.product_links             enable row level security;
alter table public.featured_requests         enable row level security;

revoke all on public.product_variations, public.product_variation_options, public.product_links, public.featured_requests from anon, authenticated;
grant select on public.product_variations, public.product_variation_options, public.product_links to anon, authenticated;
grant insert, update, delete on public.product_variations, public.product_variation_options, public.product_links to authenticated;
grant select, delete on public.featured_requests to authenticated;
grant insert (product_id, placement, days) on public.featured_requests to authenticated;

-- variations follow their product
drop policy if exists "Read with product" on public.product_variations;
create policy "Read with product" on public.product_variations for select to anon, authenticated
  using (exists (select 1 from public.products p where p.id = product_id));
drop policy if exists "Seller edits own" on public.product_variations;
create policy "Seller edits own" on public.product_variations for all to authenticated
  using (exists (select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid()))
  with check (exists (select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid()) and public.is_approved_seller());

drop policy if exists "Read with product" on public.product_variation_options;
create policy "Read with product" on public.product_variation_options for select to anon, authenticated
  using (exists (select 1 from public.product_variations v where v.id = variation_id));
drop policy if exists "Seller edits own" on public.product_variation_options;
create policy "Seller edits own" on public.product_variation_options for all to authenticated
  using (exists (select 1 from public.product_variations v join public.products p on p.id = v.product_id where v.id = variation_id and p.seller_id = auth.uid()))
  with check (exists (select 1 from public.product_variations v join public.products p on p.id = v.product_id where v.id = variation_id and p.seller_id = auth.uid()));

-- links: both products must belong to the seller
drop policy if exists "Read with product" on public.product_links;
create policy "Read with product" on public.product_links for select to anon, authenticated
  using (exists (select 1 from public.products p where p.id = product_id));
drop policy if exists "Seller edits own" on public.product_links;
create policy "Seller edits own" on public.product_links for all to authenticated
  using (exists (select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid()))
  with check (exists (select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid())
          and exists (select 1 from public.products p where p.id = linked_product_id and p.seller_id = auth.uid()));

-- featured requests: seller sees and cancels own unpaid requests; staff see all
drop policy if exists "Read featured requests" on public.featured_requests;
create policy "Read featured requests" on public.featured_requests for select to authenticated
  using (seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));
drop policy if exists "Seller requests featured" on public.featured_requests;
create policy "Seller requests featured" on public.featured_requests for insert to authenticated
  with check (seller_id = auth.uid() and public.is_approved_seller()
              and exists (select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid()));
drop policy if exists "Seller cancels unpaid request" on public.featured_requests;
create policy "Seller cancels unpaid request" on public.featured_requests for delete to authenticated
  using (seller_id = auth.uid() and status = 'awaiting_payment');

