-- Main menu (plan 5.9): the row of links under the header on shop pages, managed in Admin → Main menu.
-- Run once in Supabase → SQL Editor, AFTER 0015_contact_messages.sql. Safe to run again
-- (the starting menu is only added when the table is empty).
--
-- Link types:
--   home          Home page
--   shop          All products
--   deals         Deals of the Day (products on sale)
--   featured      Featured products
--   newest        New arrivals
--   pre_owned     Pre-owned products
--   free_delivery Products with free delivery
--   category      One category (and its sub-categories)
--   sell          "Sell an item" page
--   url           Any other address (a page on this site, or https://…)

create table if not exists public.menu_items (
  id           bigint generated by default as identity primary key,
  label        text not null check (char_length(trim(label)) between 2 and 40),
  label_bn     text check (label_bn is null or char_length(label_bn) <= 40),   -- Bangla label, for the Bangla site later
  link_type    text not null check (link_type in ('home', 'shop', 'deals', 'featured', 'newest', 'pre_owned', 'free_delivery', 'category', 'sell', 'url')),
  category_id  bigint references public.categories (id) on delete cascade,
  url          text check (url is null or url ~ '^(https://[^\s]+|[a-z0-9_-]+\.html([?#][^\s]*)?)$'),
  is_hot       boolean not null default false,   -- shown in red, like "Deals of the Day"
  sort_order   integer not null default 0,
  is_active    boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  check (link_type <> 'category' or category_id is not null),
  check (link_type <> 'url' or url is not null)
);

alter table public.menu_items enable row level security;
revoke all on public.menu_items from anon, authenticated;
grant select on public.menu_items to anon, authenticated;
grant insert, update, delete on public.menu_items to authenticated;

drop policy if exists "Anyone reads active menu items" on public.menu_items;
create policy "Anyone reads active menu items" on public.menu_items for select to anon, authenticated
  using (is_active or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));
drop policy if exists "Staff manage menu items" on public.menu_items;
create policy "Staff manage menu items" on public.menu_items for all to authenticated
  using (public.has_staff_role(array['master_admin', 'co_admin', 'editor']))
  with check (public.has_staff_role(array['master_admin', 'co_admin', 'editor']));

