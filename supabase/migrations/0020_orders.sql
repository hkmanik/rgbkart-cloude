-- Orders (plan 3.1–3.3, 4.1–4.5): cart → checkout → one order per shop, Cash on Delivery.
-- RGBKart never holds the money: the customer pays the seller on delivery. Sellers ship their own orders.
-- Run once in Supabase → SQL Editor, AFTER 0019_payments.sql. Safe to run again.

-- 1. Delivery methods (admin sets the fee and time) -----------------------------------------------------

create table if not exists public.shipping_methods (
  id          text primary key check (id in ('dhaka', 'outside', 'pickup', 'negotiated')),
  name        text not null,
  fee         numeric(10, 2) not null default 0 check (fee >= 0),
  eta         text,
  is_active   boolean not null default true,
  sort_order  integer not null default 0,
  updated_at  timestamptz not null default now()
);
insert into public.shipping_methods (id, name, fee, eta, sort_order) values
  ('dhaka', 'Inside Dhaka', 70, '1–2 days', 10),
  ('outside', 'Outside Dhaka', 130, '3–5 days', 20),
  ('pickup', 'Store pickup', 0, 'Same day', 30),
  ('negotiated', 'Agree with the seller', 0, 'Seller will call you', 40)
on conflict (id) do nothing;

alter table public.shipping_methods enable row level security;
revoke all on public.shipping_methods from anon, authenticated;
grant select on public.shipping_methods to anon, authenticated;
grant update (name, fee, eta, is_active, updated_at) on public.shipping_methods to authenticated;
drop policy if exists "Anyone reads delivery methods" on public.shipping_methods;
create policy "Anyone reads delivery methods" on public.shipping_methods for select to anon, authenticated using (true);
drop policy if exists "Admins edit delivery methods" on public.shipping_methods;
create policy "Admins edit delivery methods" on public.shipping_methods for update to authenticated
  using (public.has_staff_role(array['master_admin', 'co_admin'])) with check (public.has_staff_role(array['master_admin', 'co_admin']));

-- Shops can offer pickup from their address
alter table public.seller_details add column if not exists allow_pickup boolean not null default false;
grant update (allow_pickup) on public.seller_details to authenticated;

create or replace view public.shops as
  select s.user_id, s.shop_name, s.shop_slug, s.tagline, s.shop_description, s.logo_path, s.banner_path, s.city,
         case when p.role = 'individual' then null else s.phone_public end as phone_public,
         case when p.role = 'individual' then null else s.whatsapp end as whatsapp,
         case when p.role = 'individual' then null else s.email_public end as email_public,
         s.facebook_url, s.instagram_url, s.youtube_url, s.tiktok_url, s.website_url,
         s.vacation_mode, s.vacation_message, s.created_at, s.area,
         s.allow_pickup, case when s.allow_pickup then s.business_address end as pickup_address
  from public.seller_details s
  join public.profiles p on p.id = s.user_id
  where s.status = 'approved';
grant select on public.shops to anon, authenticated;

-- 2. Orders ------------------------------------------------------------------------------------------------

create table if not exists public.orders (
  id              bigint generated by default as identity primary key,
  order_no        text not null unique,
  customer_id     uuid not null references auth.users (id) on delete cascade,
  seller_id       uuid not null references public.profiles (id) on delete cascade,
  status          text not null default 'pending' check (status in ('pending', 'confirmed', 'packed', 'shipped', 'delivered', 'cancelled')),
  customer_name   text not null,
  phone           text not null,
  email           text,
  address         text not null,
  district        text not null,
  area            text,
  note            text,
  ship_method     text not null references public.shipping_methods (id),
  ship_fee        numeric(10, 2) not null default 0,
  subtotal        numeric(12, 2) not null,
  total           numeric(12, 2) not null,
  pay_method      text not null default 'cod' check (pay_method in ('cod')),
  tracking_note   text,
  cancel_reason   text,
  cancelled_by    text check (cancelled_by in ('customer', 'seller', 'admin')),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  confirmed_at    timestamptz, packed_at timestamptz, shipped_at timestamptz, delivered_at timestamptz, cancelled_at timestamptz
);
create index if not exists orders_customer on public.orders (customer_id, created_at desc);
create index if not exists orders_seller on public.orders (seller_id, status, created_at desc);
create index if not exists orders_created on public.orders (created_at);

create table if not exists public.order_items (
  id             bigint generated by default as identity primary key,
  order_id       bigint not null references public.orders (id) on delete cascade,
  product_id     bigint references public.products (id) on delete set null,
  variation_id   bigint references public.product_variations (id) on delete set null,
  title          text not null,
  variant_label  text,
  image_path     text,
  unit_price     numeric(12, 2) not null,
  qty            integer not null check (qty between 1 and 99),
  line_total     numeric(12, 2) not null
);
create index if not exists order_items_order on public.order_items (order_id);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;
revoke all on public.orders, public.order_items from anon, authenticated;
grant select on public.orders, public.order_items to authenticated;   -- changes only through the functions below

drop policy if exists "Read own orders" on public.orders;
create policy "Read own orders" on public.orders for select to authenticated
  using (customer_id = auth.uid() or seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));
drop policy if exists "Read own order items" on public.order_items;
create policy "Read own order items" on public.order_items for select to authenticated
  using (exists (select 1 from public.orders o where o.id = order_id
                 and (o.customer_id = auth.uid() or o.seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin', 'editor']))));

-- 3. Place an order --------------------------------------------------------------------------------------
-- p_items: [{"product_id": 1, "variation_id": null, "qty": 2}, ...]
-- p_ship:  {"<seller id>": "dhaka", ...}   (delivery choice per shop)
-- p_customer: {"name", "phone", "email", "address", "district", "area", "note"}
-- Prices, stock and delivery fees are worked out here, never trusted from the browser.
create or replace function public.place_order(p_items jsonb, p_ship jsonb, p_customer jsonb)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare
  uid uuid := auth.uid(); it jsonb; pr record; va record; vid bigint; unit numeric; qty int; lbl text; img text;
  ph text; nm text; addr text; dist text; sel uuid; m text; sm record; shop record; fee numeric; sub numeric;
  oid bigint; ono text; result jsonb := '[]'::jsonb; sellers uuid[]; nitems int := 0; tday text;
begin
  if uid is null then raise exception 'Please reload the page and try again'; end if;
  nm := trim(coalesce(p_customer->>'name', '')); addr := trim(coalesce(p_customer->>'address', '')); dist := trim(coalesce(p_customer->>'district', ''));
  ph := regexp_replace(coalesce(p_customer->>'phone', ''), '[^0-9+]', '', 'g');
  if char_length(nm) < 2 then raise exception 'Enter your name'; end if;
  if ph !~ '^(\+?880)?01[3-9][0-9]{8}$' then raise exception 'Enter a valid mobile number, like 01711000000'; end if;
  if char_length(addr) < 5 then raise exception 'Enter your full delivery address (house, road, area)'; end if;
  if dist = '' then raise exception 'Choose your district'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Your cart is empty'; end if;
  if jsonb_array_length(p_items) > 30 then raise exception 'Too many items in one order (30 at most)'; end if;
  if (select count(*) from public.orders where customer_id = uid and created_at > now() - interval '1 day') >= 20 then
    raise exception 'You have placed many orders today. Please contact us if you need more.';
  end if;

  -- work out each line, grouped by shop
  create temp table if not exists _lines (seller_id uuid, product_id bigint, variation_id bigint, title text, label text, img text, unit numeric, qty int, manage boolean, free_del boolean, ships_to text) on commit drop;
  delete from _lines;
  for it in select * from jsonb_array_elements(p_items) loop
    qty := coalesce((it->>'qty')::int, 0);
    if qty < 1 or qty > 99 then raise exception 'Choose a quantity from 1 to 99'; end if;
    select p.*, sd.vacation_mode into pr from public.products p join public.seller_details sd on sd.user_id = p.seller_id and sd.status = 'approved'
     where p.id = (it->>'product_id')::bigint for update of p;
    if pr.id is null or pr.status <> 'approved' then raise exception 'An item in your cart is no longer available. Please remove it.'; end if;
    if pr.contact_only then raise exception '"%" can''t be ordered online. Contact the seller instead.', pr.title; end if;
    if pr.is_downloadable then raise exception '"%" is a digital product and can''t be ordered yet.', pr.title; end if;
    if not pr.cod_allowed then raise exception '"%" can''t be paid by Cash on Delivery.', pr.title; end if;
    if pr.vacation_mode then raise exception 'The shop selling "%" is on holiday and not taking orders.', pr.title; end if;
    if pr.seller_id = uid then raise exception 'You can''t order your own product'; end if;
    if pr.sold_individually then qty := 1; end if;
    lbl := null; vid := null; img := (select storage_path from public.product_images where product_id = pr.id order by sort_order limit 1);
    if pr.product_type = 'variable' then
      select v.* into va from public.product_variations v where v.id = (it->>'variation_id')::bigint and v.product_id = pr.id and v.is_active for update;
      if va.id is null then raise exception 'Choose an option for "%"', pr.title; end if;
      unit := coalesce(va.sale_price, va.price); vid := va.id;
      if va.stock < qty and pr.backorders = 'no' then raise exception 'Only % left of "%"', va.stock, pr.title; end if;
      select string_agg(o.value || coalesce(' ' || a.unit, ''), ' / ' order by a.name) into lbl
        from public.product_variation_options vo join public.attribute_options o on o.id = vo.option_id join public.attributes a on a.id = vo.attribute_id
       where vo.variation_id = va.id;
      if va.image_id is not null then img := coalesce((select storage_path from public.product_images where id = va.image_id), img); end if;
      update public.product_variations set stock = greatest(stock - qty, 0) where id = va.id;
    else
      unit := case when pr.sale_price is not null and (pr.sale_starts_at is null or pr.sale_starts_at <= now())
                         and (pr.sale_ends_at is null or pr.sale_ends_at >= now()) then pr.sale_price else pr.price end;
      if pr.manage_stock and pr.stock < qty and pr.backorders = 'no' then
        if pr.stock = 0 then raise exception '"%" is out of stock', pr.title; end if;
        raise exception 'Only % left of "%"', pr.stock, pr.title;
      end if;
      if not pr.manage_stock and pr.stock_status = 'out_of_stock' then raise exception '"%" is out of stock', pr.title; end if;
      if pr.manage_stock then update public.products set stock = greatest(stock - qty, 0) where id = pr.id; end if;
    end if;
    if unit is null or unit <= 0 then raise exception '"%" has no price yet', pr.title; end if;
    insert into _lines values (pr.seller_id, pr.id, vid, pr.title, lbl, img, unit, qty, pr.manage_stock, pr.free_delivery, pr.ships_to);
    nitems := nitems + 1;
  end loop;

  -- one order per shop
  tday := to_char(now() at time zone 'Asia/Dhaka', 'YYMMDD');
  sellers := array(select distinct l.seller_id from _lines l);
  foreach sel in array sellers loop
    select * into shop from public.seller_details where user_id = sel;
    m := coalesce(p_ship->>(sel::text), 'negotiated');
    select * into sm from public.shipping_methods where id = m and is_active;
    if sm.id is null then raise exception 'Choose a delivery option for %', shop.shop_name; end if;
    if m = 'pickup' and not shop.allow_pickup then raise exception '% doesn''t offer store pickup', shop.shop_name; end if;
    if m = 'dhaka' and exists (select 1 from _lines l where l.seller_id = sel and l.ships_to = 'outside_dhaka') then raise exception 'Some items from % don''t deliver inside Dhaka', shop.shop_name; end if;
    if m = 'outside' and exists (select 1 from _lines l where l.seller_id = sel and l.ships_to = 'inside_dhaka') then raise exception 'Some items from % only deliver inside Dhaka', shop.shop_name; end if;
    sub := (select sum(l.unit * l.qty) from _lines l where l.seller_id = sel);
    fee := case when m in ('dhaka', 'outside') and not exists (select 1 from _lines l where l.seller_id = sel and not l.free_del) then 0
                when m in ('dhaka', 'outside') then sm.fee else 0 end;
    loop
      ono := 'RGB-' || tday || '-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 5));
      exit when not exists (select 1 from public.orders where order_no = ono);
    end loop;
    insert into public.orders (order_no, customer_id, seller_id, customer_name, phone, email, address, district, area, note, ship_method, ship_fee, subtotal, total)
    values (ono, uid, sel, left(nm, 80), ph, nullif(lower(trim(coalesce(p_customer->>'email', ''))), ''), left(addr, 300), left(dist, 40),
            nullif(left(trim(coalesce(p_customer->>'area', '')), 60), ''), nullif(left(trim(coalesce(p_customer->>'note', '')), 500), ''), m, fee, sub, sub + fee)
    returning id into oid;
    insert into public.order_items (order_id, product_id, variation_id, title, variant_label, image_path, unit_price, qty, line_total)
    select oid, l.product_id, l.variation_id, l.title, l.label, l.img, l.unit, l.qty, l.unit * l.qty from _lines l where l.seller_id = sel;
    result := result || jsonb_build_object('order_no', ono, 'shop', shop.shop_name, 'phone', case when shop.phone_public is not null then shop.phone_public end, 'total', sub + fee, 'ship', sm.name);
  end loop;

  -- remember the address on the customer's profile for next time
  insert into public.profiles (id) values (uid) on conflict (id) do nothing;
  update public.profiles set full_name = coalesce(nullif(full_name, ''), left(nm, 80)), phone = coalesce(nullif(phone, ''), ph) where id = uid;
  return result;
end; $$;
revoke execute on function public.place_order(jsonb, jsonb, jsonb) from public, anon;
grant  execute on function public.place_order(jsonb, jsonb, jsonb) to authenticated;

-- 4. Change an order's status -------------------------------------------------------------------------------
-- Seller (or admin): pending → confirmed → packed → shipped → delivered; cancel before delivery (with a reason).
-- Customer: cancel while pending or confirmed.
create or replace function public.update_order(p_order bigint, p_status text, p_note text default null)
returns text language plpgsql security definer set search_path = ''
as $$
declare o record; who text; steps text[] := array['pending', 'confirmed', 'packed', 'shipped', 'delivered'];
begin
  select * into o from public.orders where id = p_order for update;
  if o.id is null then raise exception 'Order not found'; end if;
  who := case when o.seller_id = auth.uid() then 'seller'
              when public.has_staff_role(array['master_admin', 'co_admin']) then 'admin'
              when o.customer_id = auth.uid() then 'customer' end;
  if who is null then raise exception 'Order not found'; end if;
  if o.status in ('delivered', 'cancelled') then raise exception 'This order is already %', o.status; end if;

  if p_status = 'cancelled' then
    if who = 'customer' and o.status not in ('pending', 'confirmed') then raise exception 'The shop has already packed this order. Please call the shop to cancel.'; end if;
    if who <> 'customer' and coalesce(trim(p_note), '') = '' then raise exception 'Give the customer a reason for cancelling'; end if;
    update public.orders set status = 'cancelled', cancelled_at = now(), cancelled_by = who, cancel_reason = nullif(trim(coalesce(p_note, '')), ''), updated_at = now() where id = o.id;
    -- put the stock back
    update public.products p set stock = p.stock + i.qty from public.order_items i
     where i.order_id = o.id and i.variation_id is null and p.id = i.product_id and p.manage_stock;
    update public.product_variations v set stock = v.stock + i.qty from public.order_items i
     where i.order_id = o.id and v.id = i.variation_id;
    return 'cancelled';
  end if;

  if who = 'customer' then raise exception 'Only the shop can change this order'; end if;
  if not (p_status = any (steps)) or array_position(steps, p_status) <= array_position(steps, o.status) then
    raise exception 'Choose a later step for this order';
  end if;
  update public.orders set status = p_status, updated_at = now(),
         tracking_note = coalesce(nullif(trim(coalesce(p_note, '')), ''), tracking_note),
         confirmed_at = case when p_status in ('confirmed', 'packed', 'shipped', 'delivered') then coalesce(confirmed_at, now()) else confirmed_at end,
         packed_at    = case when p_status in ('packed', 'shipped', 'delivered') then coalesce(packed_at, now()) else packed_at end,
         shipped_at   = case when p_status in ('shipped', 'delivered') then coalesce(shipped_at, now()) else shipped_at end,
         delivered_at = case when p_status = 'delivered' then now() else delivered_at end
   where id = o.id;
  return p_status;
end; $$;
revoke execute on function public.update_order(bigint, text, text) from public, anon;
grant  execute on function public.update_order(bigint, text, text) to authenticated;

-- 5. Order figures for Admin → Reports ------------------------------------------------------------------------
create or replace function public.admin_order_report(p_from date, p_to date)
returns jsonb language plpgsql stable security definer set search_path = ''
as $$
declare f timestamptz := p_from::timestamp at time zone 'Asia/Dhaka'; t timestamptz := (p_to + 1)::timestamp at time zone 'Asia/Dhaka';
begin
  if not public.has_staff_role(array['master_admin', 'co_admin']) then raise exception 'Only the Master Admin or a Co-admin can see reports'; end if;
  return jsonb_build_object(
    'orders',          (select count(*) from public.orders where created_at >= f and created_at < t),
    'orders_value',    (select coalesce(sum(total), 0) from public.orders where created_at >= f and created_at < t and status <> 'cancelled'),
    'delivered',       (select count(*) from public.orders where delivered_at >= f and delivered_at < t),
    'cancelled',       (select count(*) from public.orders where cancelled_at >= f and cancelled_at < t),
    'open_now',        (select count(*) from public.orders where status in ('pending', 'confirmed', 'packed', 'shipped')),
    'buyers',          (select count(distinct customer_id) from public.orders where created_at >= f and created_at < t));
end; $$;
revoke execute on function public.admin_order_report(date, date) from public, anon;
grant  execute on function public.admin_order_report(date, date) to authenticated;

