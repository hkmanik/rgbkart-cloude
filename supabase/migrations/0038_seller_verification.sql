-- Seller verification (plan 6.4).
-- A shop uploads its NID (front and back) and/or trade licence in Seller Center → Get verified. The files are private:
-- only the shop itself and RGBKart staff can open them. Staff check them in Admin → Verification and approve or reject
-- with a note. Approved shops show "✓ Verified shop" to buyers (shop page, product page, Top shops).
-- Only staff can switch the badge on or off; the shop cannot set it itself.
-- Run once in Supabase → SQL Editor, AFTER 0037_activity_log.sql. Safe to run again.

-- 1. Badge on the shop ---------------------------------------------------------------------------------------------
alter table public.seller_details add column if not exists is_verified boolean not null default false;
alter table public.seller_details add column if not exists verified_at timestamptz;

create or replace function public.verified_guard()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if public.has_staff_role(array['master_admin', 'co_admin', 'editor']) or current_user in ('postgres', 'supabase_admin') then return new; end if;
  if tg_op = 'INSERT' then new.is_verified := false; new.verified_at := null;
  else new.is_verified := old.is_verified; new.verified_at := old.verified_at; end if;
  return new;
end; $$;
drop trigger if exists verified_guard on public.seller_details;
create trigger verified_guard before insert or update on public.seller_details for each row execute function public.verified_guard();

-- 2. Documents -------------------------------------------------------------------------------------------------------
create table if not exists public.seller_verifications (
  id           bigint generated by default as identity primary key,
  seller_id    uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  doc_type     text not null check (doc_type in ('nid', 'trade_licence', 'passport', 'other')),
  doc_number   text check (doc_number is null or char_length(doc_number) <= 40),
  holder_name  text check (holder_name is null or char_length(holder_name) <= 100),
  files        text[] not null default '{}' check (cardinality(files) between 1 and 4),
  note         text check (note is null or char_length(note) <= 500),               -- from the shop
  status       text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  admin_note   text check (admin_note is null or char_length(admin_note) <= 500),
  reviewed_by  uuid,
  reviewed_at  timestamptz,
  created_at   timestamptz not null default now()
);
create index if not exists seller_verifications_seller on public.seller_verifications (seller_id, created_at desc);
create index if not exists seller_verifications_status on public.seller_verifications (status, created_at);

alter table public.seller_verifications enable row level security;
revoke all on public.seller_verifications from anon, authenticated;
grant select on public.seller_verifications to authenticated;     -- changes only through the functions below
drop policy if exists "Own documents and staff" on public.seller_verifications;
create policy "Own documents and staff" on public.seller_verifications for select to authenticated
  using (seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('seller-docs', 'seller-docs', false, 5242880, array['image/jpeg', 'image/png', 'image/webp', 'application/pdf'])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
drop policy if exists "Sellers upload own documents" on storage.objects;
create policy "Sellers upload own documents" on storage.objects for insert to authenticated
  with check (bucket_id = 'seller-docs' and (storage.foldername(name))[1] = auth.uid()::text and public.is_seller());
drop policy if exists "Documents for the shop and staff" on storage.objects;
create policy "Documents for the shop and staff" on storage.objects for select to authenticated
  using (bucket_id = 'seller-docs' and ((storage.foldername(name))[1] = auth.uid()::text or public.has_staff_role(array['master_admin', 'co_admin', 'editor'])));
drop policy if exists "Sellers delete own documents" on storage.objects;
create policy "Sellers delete own documents" on storage.objects for delete to authenticated
  using (bucket_id = 'seller-docs' and (storage.foldername(name))[1] = auth.uid()::text);

-- 3. Shop sends documents ---------------------------------------------------------------------------------------------
create or replace function public.submit_verification(p_doc_type text, p_doc_number text, p_holder text, p_files text[], p_note text default null)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare f text[]; rid bigint;
begin
  if auth.uid() is null or not exists (select 1 from public.seller_details where user_id = auth.uid()) then raise exception 'Only shops can ask to be verified'; end if;
  if exists (select 1 from public.seller_details where user_id = auth.uid() and is_verified) then raise exception 'Your shop is already verified'; end if;
  if exists (select 1 from public.seller_verifications where seller_id = auth.uid() and status = 'pending') then raise exception 'Your documents are already waiting to be checked'; end if;
  if p_doc_type not in ('nid', 'trade_licence', 'passport', 'other') then raise exception 'Choose the document type'; end if;
  f := coalesce((select array_agg(x) from unnest(coalesce(p_files, '{}')) x where x like auth.uid()::text || '/%'), '{}');
  if cardinality(f) = 0 then raise exception 'Add a photo or PDF of the document'; end if;
  if cardinality(f) > 4 then raise exception 'Up to 4 files'; end if;
  insert into public.seller_verifications (seller_id, doc_type, doc_number, holder_name, files, note)
  values (auth.uid(), p_doc_type, nullif(trim(coalesce(p_doc_number, '')), ''), nullif(trim(coalesce(p_holder, '')), ''), f, nullif(trim(coalesce(p_note, '')), ''))
  returning id into rid;
  return rid;
end; $$;
revoke execute on function public.submit_verification(text, text, text, text[], text) from public, anon;
grant  execute on function public.submit_verification(text, text, text, text[], text) to authenticated;

-- 4. Staff decide (and can take the badge away later) -----------------------------------------------------------------
create or replace function public.admin_review_verification(p_id bigint, p_approve boolean, p_note text default null)
returns void language plpgsql security definer set search_path = ''
as $$
declare v record; n text := nullif(trim(coalesce(p_note, '')), '');
begin
  if not public.has_staff_role(array['master_admin', 'co_admin', 'editor']) then raise exception 'Only RGBKart staff can do this'; end if;
  select * into v from public.seller_verifications where id = p_id for update;
  if v.id is null then raise exception 'Not found'; end if;
  if v.status <> 'pending' then raise exception 'This was already checked'; end if;
  if not p_approve and n is null then raise exception 'Tell the shop what is wrong with the document'; end if;
  update public.seller_verifications set status = case when p_approve then 'approved' else 'rejected' end, admin_note = n,
         reviewed_by = auth.uid(), reviewed_at = now() where id = p_id;
  if p_approve then
    update public.seller_details set is_verified = true, verified_at = now() where user_id = v.seller_id;
  end if;
  perform public.notify(v.seller_id, case when p_approve then 'verify_ok' else 'verify_no' end,
    case when p_approve then 'Your shop is now verified ✓' else 'Verification: please send your document again' end,
    coalesce(n, case when p_approve then 'Buyers now see "Verified shop" on your shop and products.' else '' end), 'seller.html#verify', 'verify:' || p_id);
end; $$;
revoke execute on function public.admin_review_verification(bigint, boolean, text) from public, anon;
grant  execute on function public.admin_review_verification(bigint, boolean, text) to authenticated;

create or replace function public.admin_set_verified(p_seller uuid, p_on boolean)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if not public.has_staff_role(array['master_admin', 'co_admin']) then raise exception 'Only the Master Admin or a Co-admin can do this'; end if;
  update public.seller_details set is_verified = coalesce(p_on, false), verified_at = case when p_on then now() end where user_id = p_seller;
end; $$;
revoke execute on function public.admin_set_verified(uuid, boolean) from public, anon;
grant  execute on function public.admin_set_verified(uuid, boolean) to authenticated;

-- Staff hear about new documents
create or replace function public.alerts_verifications()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare st record; shop text;
begin
  select shop_name into shop from public.seller_details where user_id = new.seller_id;
  for st in select distinct user_id from public.staff where staff_role in ('master_admin', 'co_admin', 'editor') loop
    perform public.notify(st.user_id, 'verify_new', format('Verification to check: %s', coalesce(shop, 'a shop')),
      replace(new.doc_type, '_', ' '), 'admin.html#verify', 'verify:' || new.id);
  end loop;
  return null;
end; $$;
drop trigger if exists alerts_verifications on public.seller_verifications;
create trigger alerts_verifications after insert on public.seller_verifications for each row execute function public.alerts_verifications();
do $$ begin
  if to_regprocedure('public.log_staff_action()') is not null then
    drop trigger if exists log_staff_action on public.seller_verifications;
    create trigger log_staff_action after insert or update or delete on public.seller_verifications for each row execute function public.log_staff_action();
  end if;
end $$;

-- 5. Badge for shoppers: shops view and Top shops ---------------------------------------------------------------------
create or replace view public.shops as
  select s.user_id, s.shop_name, s.shop_slug, s.tagline, s.shop_description, s.logo_path, s.banner_path, s.city,
         case when p.role = 'individual' then null else s.phone_public end as phone_public,
         case when p.role = 'individual' then null else s.whatsapp end as whatsapp,
         case when p.role = 'individual' then null else s.email_public end as email_public,
         s.facebook_url, s.instagram_url, s.youtube_url, s.tiktok_url, s.website_url,
         s.vacation_mode, s.vacation_message, s.created_at, s.area,
         s.allow_pickup, case when s.allow_pickup then s.business_address end as pickup_address,
         s.shop_name_bn, s.rating_avg, s.rating_count, s.is_verified
  from public.seller_details s
  join public.profiles p on p.id = s.user_id
  where s.status = 'approved';
grant select on public.shops to anon, authenticated;

drop function if exists public.top_shops(integer);
create function public.top_shops(p_limit integer default 12)
returns table (user_id uuid, shop_name text, shop_name_bn text, shop_slug text, tagline text, logo_path text, banner_path text,
               city text, area text, featured_count integer, product_count integer, rating_avg numeric, rating_count integer, is_verified boolean)
language sql stable security definer set search_path = ''
as $$
  select s.user_id, s.shop_name, s.shop_name_bn, s.shop_slug, s.tagline, s.logo_path, s.banner_path, s.city, s.area,
         count(*) filter (where p.is_featured)::int, count(*)::int, s.rating_avg, s.rating_count, s.is_verified
  from public.seller_details s
  join public.profiles pr on pr.id = s.user_id and pr.role = 'seller'
  join public.products p on p.seller_id = s.user_id and p.status = 'approved'
  where s.status = 'approved' and not coalesce(s.vacation_mode, false)
  group by s.user_id
  order by count(*) filter (where p.is_featured) desc, count(*) desc, max(p.published_at) desc nulls last
  limit greatest(1, least(coalesce(p_limit, 12), 48))
$$;
grant execute on function public.top_shops(integer) to anon, authenticated;

select to_regclass('public.seller_verifications') is not null as verification_ready,
       (select count(*) from public.seller_details where is_verified) as verified_shops;
