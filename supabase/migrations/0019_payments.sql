-- Payments (plan 5.6 / 5.7): sellers pay Featured and ad fees by bKash, Nagad, Upay or Rocket and enter the
-- Transaction ID (TrxID); admin checks and verifies in Admin → Payments, which starts the Featured listing or ad.
-- Shops and one-time sellers can also book ads themselves.
-- Run once in Supabase → SQL Editor, AFTER 0018_admin_tools.sql. Safe to run again.
--
-- A Transaction ID can be used only ONCE on RGBKart (capital letters and spaces don't matter).
-- The only exception: after admin rejects a payment, the same seller may send the same TrxID again for the same item
-- (for example when the money arrived late).

-- 1. Where sellers send money (admin fills in the numbers) -------------------------------------------

create table if not exists public.payment_methods (
  id            text primary key check (id ~ '^[a-z]{2,20}$'),
  name          text not null,
  account_no    text,
  account_type  text not null default 'personal' check (account_type in ('personal', 'merchant', 'agent')),
  instructions  text check (instructions is null or char_length(instructions) <= 300),
  color         text not null default '#E2136E',
  is_active     boolean not null default false,
  sort_order    integer not null default 0,
  updated_at    timestamptz not null default now(),
  check (not is_active or account_no is not null)
);
insert into public.payment_methods (id, name, color, sort_order) values
  ('bkash', 'bKash', '#E2136E', 10), ('nagad', 'Nagad', '#F6921E', 20), ('upay', 'Upay', '#003C71', 30), ('rocket', 'Rocket', '#8C3494', 40)
on conflict (id) do nothing;

alter table public.payment_methods enable row level security;
revoke all on public.payment_methods from anon, authenticated;
grant select on public.payment_methods to anon, authenticated;
grant update (account_no, account_type, instructions, is_active, updated_at) on public.payment_methods to authenticated;
drop policy if exists "Anyone reads active methods" on public.payment_methods;
create policy "Anyone reads active methods" on public.payment_methods for select to anon, authenticated
  using (is_active or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));
drop policy if exists "Admins edit methods" on public.payment_methods;
create policy "Admins edit methods" on public.payment_methods for update to authenticated
  using (public.has_staff_role(array['master_admin', 'co_admin'])) with check (public.has_staff_role(array['master_admin', 'co_admin']));

-- 2. Payments sent by sellers -------------------------------------------------------------------------

create table if not exists public.payments (
  id                   bigint generated by default as identity primary key,
  kind                 text not null check (kind in ('featured', 'ad')),
  featured_request_id  bigint references public.featured_requests (id) on delete set null,
  ad_id                bigint references public.ads (id) on delete set null,
  item_title           text,                               -- product title or ad headline, kept for the record
  seller_id            uuid not null references public.profiles (id) on delete cascade,
  amount               numeric(12, 2) not null check (amount > 0),
  method_id            text not null references public.payment_methods (id),
  paid_to              text,                               -- the RGBKart number shown to the seller at the time
  sender_no            text not null,
  trx_id               text not null check (trx_id ~ '^[A-Z0-9]{6,20}$'),
  status               text not null default 'review' check (status in ('review', 'verified', 'rejected')),
  reject_reason        text,
  created_at           timestamptz not null default now(),
  reviewed_by          uuid references auth.users (id) on delete set null,
  reviewed_at          timestamptz,
  check ((kind = 'featured') = (featured_request_id is not null) or status <> 'review'),
  check ((kind = 'ad') = (ad_id is not null) or status <> 'review')
);
-- A TrxID can only be live once (waiting for check, or verified)
create unique index if not exists payments_trx_once on public.payments (trx_id) where status <> 'rejected';
create index if not exists payments_status on public.payments (status, created_at);
create index if not exists payments_seller on public.payments (seller_id, created_at desc);

alter table public.payments enable row level security;
revoke all on public.payments from anon, authenticated;
grant select on public.payments to authenticated;
drop policy if exists "Seller and staff read payments" on public.payments;
create policy "Seller and staff read payments" on public.payments for select to authenticated
  using (seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));

-- Make a TrxID comparable: capitals, no spaces or dashes
create or replace function public.clean_trx(p text)
returns text language sql immutable set search_path = ''
as $$ select upper(regexp_replace(coalesce(p, ''), '[^A-Za-z0-9]', '', 'g')) $$;

-- Seller sends a payment for their Featured request or ad
create or replace function public.submit_payment(p_kind text, p_ref bigint, p_method text, p_sender text, p_trx text)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare uid uuid := auth.uid(); trx text := public.clean_trx(p_trx); snd text; m record; fr record; ad record; amt numeric; title text; pid bigint;
begin
  if uid is null then raise exception 'Please reload the page and try again'; end if;
  select * into m from public.payment_methods where id = p_method and is_active;
  if m.id is null then raise exception 'Choose how you paid'; end if;
  snd := regexp_replace(coalesce(p_sender, ''), '[^0-9+]', '', 'g');
  if snd !~ '^(\+?880)?01[3-9][0-9]{8}$' then raise exception 'Enter the mobile number you paid from, like 01711000000'; end if;
  if trx !~ '^[A-Z0-9]{6,20}$' then raise exception 'Enter the Transaction ID (TrxID) from your payment message. It has 6 to 20 letters and numbers.'; end if;

  if p_kind = 'featured' then
    select f.*, p.title as ptitle into fr from public.featured_requests f join public.products p on p.id = f.product_id
     where f.id = p_ref and f.seller_id = uid for update of f;
    if fr.id is null then raise exception 'Featured request not found'; end if;
    if fr.status = 'payment_submitted' then raise exception 'You already sent a payment for this. Please wait for our team to check it.'; end if;
    if fr.status <> 'awaiting_payment' then raise exception 'This Featured request doesn''t need a payment now'; end if;
    amt := fr.price; title := fr.ptitle;
  elsif p_kind = 'ad' then
    select * into ad from public.ads where id = p_ref and seller_id = uid for update;
    if ad.id is null then raise exception 'Ad not found'; end if;
    if ad.payment_status <> 'unpaid' then raise exception 'This ad doesn''t need a payment'; end if;
    if exists (select 1 from public.payments where ad_id = ad.id and status = 'review') then
      raise exception 'You already sent a payment for this. Please wait for our team to check it.';
    end if;
    amt := ad.amount; title := ad.title;
  else
    raise exception 'Unknown payment';
  end if;
  if amt is null or amt <= 0 then raise exception 'There is nothing to pay for this'; end if;

  -- The same TrxID can never be used twice (except re-sending your own rejected payment for the same item)
  if exists (select 1 from public.payments where trx_id = trx
              and (status <> 'rejected' or seller_id <> uid
                   or coalesce(featured_request_id, -1) <> coalesce(case when p_kind = 'featured' then p_ref end, -1)
                   or coalesce(ad_id, -1) <> coalesce(case when p_kind = 'ad' then p_ref end, -1))) then
    raise exception 'This Transaction ID has already been used. Check the TrxID in your payment message.';
  end if;

  insert into public.payments (kind, featured_request_id, ad_id, item_title, seller_id, amount, method_id, paid_to, sender_no, trx_id)
  values (p_kind, case when p_kind = 'featured' then p_ref end, case when p_kind = 'ad' then p_ref end, title, uid, amt, m.id, m.account_no, snd, trx)
  returning id into pid;
  if p_kind = 'featured' then update public.featured_requests set status = 'payment_submitted' where id = p_ref; end if;
  return pid;
exception when unique_violation then
  raise exception 'This Transaction ID has already been used. Check the TrxID in your payment message.';
end; $$;
revoke execute on function public.submit_payment(text, bigint, text, text, text) from public, anon;
grant  execute on function public.submit_payment(text, bigint, text, text, text) to authenticated;

-- Admin checks the money arrived: verify (starts the Featured listing or ad) or reject with a reason
create or replace function public.admin_verify_payment(p_payment bigint, p_ok boolean, p_reason text default null)
returns text language plpgsql security definer set search_path = ''
as $$
declare pay record; fr record; ad record; today date := (now() at time zone 'Asia/Dhaka')::date; n int;
begin
  if not public.has_staff_role(array['master_admin', 'co_admin']) then raise exception 'Only the Master Admin or a Co-admin can check payments'; end if;
  select * into pay from public.payments where id = p_payment for update;
  if pay.id is null then raise exception 'Payment not found'; end if;
  if pay.status <> 'review' then raise exception 'This payment was already %', pay.status; end if;

  if not p_ok then
    if coalesce(trim(p_reason), '') = '' then raise exception 'Give the seller a reason'; end if;
    update public.payments set status = 'rejected', reject_reason = trim(p_reason), reviewed_by = auth.uid(), reviewed_at = now() where id = pay.id;
    if pay.kind = 'featured' then
      update public.featured_requests set status = 'awaiting_payment' where id = pay.featured_request_id and status = 'payment_submitted';
    end if;
    return 'rejected';
  end if;

  if pay.kind = 'featured' then
    select f.*, p.status as pstatus into fr from public.featured_requests f join public.products p on p.id = f.product_id where f.id = pay.featured_request_id for update of f;
    if fr.id is null then raise exception 'The Featured request no longer exists'; end if;
    if fr.pstatus <> 'approved' then raise exception 'Approve the product first (Products page), then verify the payment'; end if;
    update public.featured_requests set status = 'active', starts_at = now(), ends_at = now() + make_interval(days => fr.days), price = pay.amount
     where id = fr.id;
    update public.products set is_featured = true where id = fr.product_id;
  else
    select * into ad from public.ads where id = pay.ad_id for update;
    if ad.id is null then raise exception 'The ad no longer exists'; end if;
    n := ad.ends_on - ad.starts_on;                      -- keep the number of days the seller paid for
    update public.ads set payment_status = 'paid', is_active = true,
           starts_on = greatest(ad.starts_on, today), ends_on = greatest(ad.starts_on, today) + n
     where id = ad.id;
  end if;
  update public.payments set status = 'verified', reviewed_by = auth.uid(), reviewed_at = now() where id = pay.id;
  return 'verified';
end; $$;
revoke execute on function public.admin_verify_payment(bigint, boolean, text) from public, anon;
grant  execute on function public.admin_verify_payment(bigint, boolean, text) to authenticated;

-- Older buttons in Featured & ads ("Payment received: start", "Reject") also settle a payment that is waiting
create or replace function public.payments_follow_request()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if new.status = 'active' and old.status in ('awaiting_payment', 'payment_submitted') then
    update public.payments set status = 'verified', reviewed_by = auth.uid(), reviewed_at = now()
     where featured_request_id = new.id and status = 'review';
  elsif new.status in ('rejected', 'cancelled') and old.status = 'payment_submitted' then
    update public.payments set status = 'rejected', reject_reason = coalesce(reject_reason, 'Featured request was ' || new.status), reviewed_by = auth.uid(), reviewed_at = now()
     where featured_request_id = new.id and status = 'review';
  end if;
  return new;
end; $$;
drop trigger if exists payments_follow_request on public.featured_requests;
create trigger payments_follow_request after update of status on public.featured_requests
  for each row execute function public.payments_follow_request();

-- 3. Sellers book ads themselves ------------------------------------------------------------------------

alter table public.ads drop constraint if exists ads_image_path_check;
alter table public.ads add constraint ads_image_path_check check (image_path is null or image_path ~ '^(admin|[0-9a-f-]{36})/[A-Za-z0-9/_.-]+$');

drop policy if exists "Sellers read own ads" on public.ads;
create policy "Sellers read own ads" on public.ads for select to authenticated using (seller_id = auth.uid());
drop policy if exists "Sellers delete own unpaid ads" on public.ads;
create policy "Sellers delete own unpaid ads" on public.ads for delete to authenticated
  using (seller_id = auth.uid() and payment_status = 'unpaid' and not is_active
         and not exists (select 1 from public.payments p where p.ad_id = ads.id and p.status = 'review'));

create or replace function public.seller_book_ad(p_placement text, p_title text, p_subtitle text, p_cta text, p_link text,
                                                 p_color text, p_image text, p_start date, p_days integer)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare uid uuid := auth.uid(); r record; today date := (now() at time zone 'Asia/Dhaka')::date; aid bigint;
begin
  if uid is null or not public.is_approved_seller() then raise exception 'Only approved sellers can book ads'; end if;
  select * into r from public.ad_rates where placement = p_placement and is_active;
  if r.placement is null then raise exception 'That ad space is not available'; end if;
  if p_days is null or p_days < r.min_days or p_days > 90 then raise exception 'Choose between % and 90 days', r.min_days; end if;
  if p_start is null or p_start < today or p_start > today + 60 then raise exception 'Choose a start date within the next 60 days'; end if;
  if char_length(trim(coalesce(p_title, ''))) < 2 then raise exception 'Write a headline'; end if;
  if p_image is not null and p_image !~ ('^' || uid::text || '/ads/[A-Za-z0-9_.-]+$') then raise exception 'Picture upload problem. Please try again.'; end if;
  if (select count(*) from public.ads where seller_id = uid and payment_status = 'unpaid' and not is_active) >= 3 then
    raise exception 'You have 3 ads waiting for payment. Pay for one or delete one first.';
  end if;
  insert into public.ads (placement, seller_id, title, subtitle, cta, link_url, image_path, color, starts_on, ends_on, price_per_day, amount, payment_status, is_active, created_by)
  values (r.placement, uid, trim(p_title), nullif(trim(coalesce(p_subtitle, '')), ''), coalesce(nullif(trim(coalesce(p_cta, '')), ''), 'Shop now'),
          coalesce(nullif(trim(coalesce(p_link, '')), ''), 'browse.html'), p_image, coalesce(p_color, 'green'),
          p_start, p_start + p_days - 1, r.price_per_day, r.price_per_day * p_days, 'unpaid', false, uid)
  returning id into aid;
  return aid;
end; $$;
revoke execute on function public.seller_book_ad(text, text, text, text, text, text, text, date, integer) from public, anon;
grant  execute on function public.seller_book_ad(text, text, text, text, text, text, text, date, integer) to authenticated;

-- 4. Check -------------------------------------------------------------------------------------------------
select (select count(*) from public.payment_methods) as payment_methods,
       to_regclass('public.payments') is not null as payments_ready,
       to_regprocedure('public.seller_book_ad(text,text,text,text,text,text,text,date,integer)') is not null as ad_booking_ready;
