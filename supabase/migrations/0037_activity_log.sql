-- Admin activity log (plan 5.11): who on the RGBKart team changed what, and when.
-- Every add / change / delete made by a staff member (Master Admin, Co-admin, Editor) on the important tables is written
-- here automatically by the database, whichever page or tool did it. Shoppers' and sellers' own actions are not logged.
-- Only the Master Admin and Co-admins can read it (Admin → Activity log). Nobody can edit or delete entries.
-- Run once in Supabase → SQL Editor, AFTER 0036_returns.sql. Safe to run again.

-- (Also: the last missing Bangla category name)
update public.categories set name_bn = 'পানি দেওয়া ও সেচের সরঞ্জাম' where name_bn is null and lower(trim(name)) = 'watering & irrigation supplies';

create table if not exists public.activity_log (
  id           bigint generated by default as identity primary key,
  at           timestamptz not null default now(),
  actor_id     uuid,
  actor_email  text,
  actor_role   text,
  table_name   text not null,
  action       text not null check (action in ('add', 'change', 'delete')),
  row_key      text,
  label        text,                -- e.g. product title, shop name, order number
  changes      jsonb                -- for changes: {"column": {"from": …, "to": …}}; for add/delete: the main fields
);
create index if not exists activity_log_at on public.activity_log (at desc);
create index if not exists activity_log_actor on public.activity_log (actor_id, at desc);
create index if not exists activity_log_table on public.activity_log (table_name, at desc);

alter table public.activity_log enable row level security;
revoke all on public.activity_log from anon, authenticated;
grant select on public.activity_log to authenticated;
drop policy if exists "Master Admin and Co-admins read the log" on public.activity_log;
create policy "Master Admin and Co-admins read the log" on public.activity_log for select to authenticated
  using (public.has_staff_role(array['master_admin', 'co_admin']));

create or replace function public.log_staff_action()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  st record; o jsonb; n jsonb; r jsonb; k text; ch jsonb := '{}'::jsonb; lbl text;
  skip text[] := array['updated_at', 'rating_avg', 'rating_count', 'used_count', 'search_vector', 'last_message_at'];
begin
  if auth.uid() is null then return null; end if;
  select s.email, s.staff_role into st from public.staff s where s.user_id = auth.uid() limit 1;
  if st.staff_role is null then return null; end if;           -- not a staff member: not logged

  o := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end;
  n := case when tg_op in ('UPDATE', 'INSERT') then to_jsonb(new) end;
  r := coalesce(n, o);
  if tg_op = 'UPDATE' then
    for k in select jsonb_object_keys(n) loop
      if k = any (skip) then continue; end if;
      if (o -> k) is distinct from (n -> k) then
        ch := ch || jsonb_build_object(k, jsonb_build_object('from', left(coalesce(o ->> k, ''), 200), 'to', left(coalesce(n ->> k, ''), 200)));
      end if;
    end loop;
    if ch = '{}'::jsonb then return null; end if;               -- nothing worth logging changed
  else
    select coalesce(jsonb_object_agg(e.key, left(e.value #>> '{}', 200)), '{}'::jsonb) into ch
      from jsonb_each(r) e
     where e.key not in ('description', 'description_bn', 'shop_description', 'search_vector', 'created_at', 'updated_at')
       and e.value is not null and e.value <> 'null'::jsonb and jsonb_typeof(e.value) not in ('object', 'array');
  end if;
  lbl := coalesce(r ->> 'title', r ->> 'shop_name', r ->> 'order_no', r ->> 'name', r ->> 'label', r ->> 'code',
                  r ->> 'email', r ->> 'full_name', r ->> 'trx_id', r ->> 'question', r ->> 'comment');
  insert into public.activity_log (actor_id, actor_email, actor_role, table_name, action, row_key, label, changes)
  values (auth.uid(), st.email, st.staff_role, tg_table_name,
          case tg_op when 'INSERT' then 'add' when 'UPDATE' then 'change' else 'delete' end,
          coalesce(r ->> 'id', r ->> 'user_id'), left(lbl, 160), ch);
  return null;
end; $$;

-- Attach to the tables staff work on (only tables that exist are used, so this runs on any version)
do $$
declare t text;
begin
  foreach t in array array['products', 'categories', 'attributes', 'attribute_options', 'category_attributes', 'areas',
                           'home_sections', 'menu_items', 'featured_plans', 'featured_requests', 'ad_rates', 'ads',
                           'payment_methods', 'payments', 'shipping_methods', 'seller_details', 'profiles', 'staff', 'staff_invites',
                           'reviews', 'product_questions', 'reports', 'return_requests', 'orders', 'product_images', 'shop_coupons'] loop
    if to_regclass('public.' || t) is not null then
      execute format('drop trigger if exists log_staff_action on public.%I', t);
      execute format('create trigger log_staff_action after insert or update or delete on public.%I for each row execute function public.log_staff_action()', t);
    end if;
  end loop;
end $$;

-- People list for the filter
create or replace function public.activity_log_people()
returns table (actor_id uuid, actor_email text, actor_role text, actions bigint, last_at timestamptz)
language sql stable security definer set search_path = ''
as $$
  select l.actor_id, max(l.actor_email), max(l.actor_role), count(*), max(l.at)
  from public.activity_log l
  where public.has_staff_role(array['master_admin', 'co_admin'])
  group by l.actor_id order by max(l.at) desc
$$;
revoke execute on function public.activity_log_people() from public, anon;
grant  execute on function public.activity_log_people() to authenticated;

select to_regclass('public.activity_log') is not null as activity_log_ready,
       (select count(*) from pg_trigger where tgname = 'log_staff_action') as tables_watched;
