#   sale        sale price (15% off)                    flash      sale that ends in 2 days (Deals of the Day)
#   neg         price negotiable                        freedel    free delivery
#   low         only 2 left (low stock)                 oos        out of stock
#   preorder    pre-order (ships later, 30% advance)    backorder  can be ordered when out of stock
#   bulk        lower price when buying more            nocod      no cash on delivery (can't be ordered yet)
#   dhaka       delivers inside Dhaka only              outside    delivers outside Dhaka only
#   svc         a service (done at the customer's place) single    one per order
#   small / large / heavy / fragile   shipping class
#   same / d35 / d610                 ships same day / in 3-5 days / in 6-10 days (default 1-2 days)
#   ret0 / ret3 / ret15 / ret30       return policy (default 7 days)
# variations: {attribute: [option values]}; every combination becomes one version. vprice: {option value: extra taka}

