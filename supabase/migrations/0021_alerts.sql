-- Alerts (plan 3.7 and more): RGBKart writes an alert for each important event into an outbox.
-- People see them on the Alerts page, and the "send-alerts" sender (Supabase Edge Function) emails them via Resend.
-- Run once in Supabase → SQL Editor, AFTER 0020_orders.sql. Safe to run again.
--
-- Alerts:
--   shops / sellers: new order, order cancelled by the customer, payment verified / not accepted,
--                    listing approved / not approved, shop approved, new message, Featured or ad ends in 2 days
--   customers:       order placed, confirmed, packed, shipped, delivered, cancelled, new message

-- 1. Outbox ----------------------------------------------------------------------------------------------

create table if not exists public.notifications (
  id             bigint generated by default as identity primary key,
  user_id        uuid references auth.users (id) on delete cascade,     -- who sees it on the Alerts page
  email          text,                                                   -- where the email goes (empty = no email)
  kind           text not null,
  title          text not null,
  body           text,
  link           text,                                                   -- page on the site, e.g. orders.html
  ref            text,                                                   -- e.g. order:12, used to avoid duplicates
  created_at     timestamptz not null default now(),
  read_at        timestamptz,
  email_status   text not null default 'pending' check (email_status in ('pending', 'sent', 'failed', 'skipped')),
  email_sent_at  timestamptz,
  email_error    text,
  attempts       integer not null default 0
);
create index if not exists notifications_user on public.notifications (user_id, created_at desc);
create index if not exists notifications_pending on public.notifications (created_at) where email_status = 'pending';
create index if not exists notifications_ref on public.notifications (ref, user_id, created_at desc);

alter table public.notifications enable row level security;
revoke all on public.notifications from anon, authenticated;
grant select on public.notifications to authenticated;
drop policy if exists "Read own alerts" on public.notifications;
create policy "Read own alerts" on public.notifications for select to authenticated using (user_id = auth.uid());

-- Each person can switch alert emails off (alerts still show on the site)
alter table public.profiles add column if not exists email_alerts boolean not null default true;

create or replace function public.set_email_alerts(p_on boolean)
returns void language sql security definer set search_path = ''
as $$ update public.profiles set email_alerts = coalesce(p_on, true) where id = auth.uid() $$;
revoke execute on function public.set_email_alerts(boolean) from public, anon;
grant  execute on function public.set_email_alerts(boolean) to authenticated;

create or replace function public.mark_alerts_read()
returns void language sql security definer set search_path = ''
as $$ update public.notifications set read_at = now() where user_id = auth.uid() and read_at is null $$;
revoke execute on function public.mark_alerts_read() from public, anon;
grant  execute on function public.mark_alerts_read() to authenticated;

create or replace function public.my_alert_count()
returns integer language sql stable security definer set search_path = ''
as $$ select count(*)::int from public.notifications where user_id = auth.uid() and read_at is null $$;
grant execute on function public.my_alert_count() to authenticated;

-- 2. Who gets the email --------------------------------------------------------------------------------------
-- Account email for normal accounts; the email a one-time seller typed in; nothing if they switched emails off.
create or replace function public.alert_email(p_user uuid)
returns text language sql stable security definer set search_path = ''
as $$
  select case when coalesce(p.email_alerts, true) = false then null
              else coalesce(case when coalesce(u.is_anonymous, false) then null else nullif(u.email, '') end, nullif(s.email_public, '')) end
  from auth.users u
  left join public.profiles p on p.id = u.id
  left join public.seller_details s on s.user_id = u.id
  where u.id = p_user
$$;
revoke execute on function public.alert_email(uuid) from public, anon, authenticated;

-- Internal: write one alert. p_email overrides the address (e.g. the email typed at checkout).
create or replace function public.notify(p_user uuid, p_kind text, p_title text, p_body text, p_link text, p_ref text default null, p_email text default null)
returns void language plpgsql security definer set search_path = ''
as $$
declare em text;
begin
  if p_user is null and p_email is null then return; end if;
  em := coalesce(case when p_user is not null then public.alert_email(p_user) end,
                 case when p_user is null or coalesce((select email_alerts from public.profiles where id = p_user), true) then nullif(lower(trim(coalesce(p_email, ''))), '') end);
  insert into public.notifications (user_id, email, kind, title, body, link, ref, email_status)
  values (p_user, em, p_kind, left(p_title, 140), left(p_body, 1000), p_link, p_ref, case when em is null then 'skipped' else 'pending' end);
end; $$;
revoke execute on function public.notify(uuid, text, text, text, text, text, text) from public, anon, authenticated;

-- 3. Events ----------------------------------------------------------------------------------------------------

-- Orders
create or replace function public.alerts_orders()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare shop text; items text; st text;
begin
  select shop_name into shop from public.seller_details where user_id = new.seller_id;
  select string_agg(qty || ' × ' || title, ', ') into items from public.order_items where order_id = new.id;
  if tg_op = 'INSERT' then
    return new;   -- order_items are added after the order row; the "placed" alerts are sent by alerts_order_items below
  end if;
  if new.status is distinct from old.status then
    st := case new.status when 'confirmed' then 'confirmed' when 'packed' then 'packed and ready to send' when 'shipped' then 'on the way'
                          when 'delivered' then 'delivered' when 'cancelled' then 'cancelled' end;
    if st is not null and coalesce(new.cancelled_by, '') <> 'customer' then
      perform public.notify(new.customer_id, 'order_' || new.status, format('Order %s is %s', new.order_no, st),
        case new.status
          when 'shipped' then format('%s has sent your order%s. Please keep %s ready in cash.', shop, coalesce(' (' || new.tracking_note || ')', ''), '৳' || to_char(new.total, 'FM99,99,99,990'))
          when 'cancelled' then format('%s cancelled your order%s.', shop, coalesce(': ' || new.cancel_reason, ''))
          when 'delivered' then format('Thank you for shopping with %s on RGBKart.', shop)
          else format('%s · %s', shop, coalesce(items, '')) end,
        'orders.html', 'order:' || new.id, new.email);
    end if;
    if new.status = 'cancelled' and new.cancelled_by = 'customer' then
      perform public.notify(new.seller_id, 'order_cancelled', format('Order %s was cancelled by the customer', new.order_no),
        format('%s · %s%s', new.customer_name, coalesce(items, ''), coalesce('. Reason: ' || new.cancel_reason, '')), 'seller.html#orders', 'order:' || new.id);
    end if;
  end if;
  return new;
end; $$;
drop trigger if exists alerts_orders on public.orders;
create trigger alerts_orders after update of status on public.orders for each row execute function public.alerts_orders();

-- "Order placed": sent once per order, after its items are saved
create or replace function public.alerts_order_items()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare o record; shop text; items text;
begin
  for o in select distinct ord.* from public.orders ord join new_items ni on ni.order_id = ord.id loop
    if exists (select 1 from public.notifications where ref = 'order:' || o.id and kind = 'order_new') then continue; end if;
    select shop_name into shop from public.seller_details where user_id = o.seller_id;
    select string_agg(qty || ' × ' || title, ', ') into items from public.order_items where order_id = o.id;
    perform public.notify(o.seller_id, 'order_new', format('New order %s · ৳%s', o.order_no, to_char(o.total, 'FM99,99,99,990')),
      format('%s (%s, %s) ordered %s. Call them to confirm.', o.customer_name, o.phone, o.district, coalesce(items, '')), 'seller.html#orders', 'order:' || o.id);
    perform public.notify(o.customer_id, 'order_placed', format('Order %s placed with %s', o.order_no, shop),
      format('%s. Total ৳%s, paid in cash on delivery. The shop will call you to confirm.', coalesce(items, ''), to_char(o.total, 'FM99,99,99,990')),
      'orders.html', 'order:' || o.id, o.email);
  end loop;
  return null;
end; $$;
drop trigger if exists alerts_order_items on public.order_items;
create trigger alerts_order_items after insert on public.order_items referencing new table as new_items
  for each statement execute function public.alerts_order_items();

-- Payments checked by admin
create or replace function public.alerts_payments()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if new.status = old.status then return new; end if;
  if new.status = 'verified' then
    perform public.notify(new.seller_id, 'payment_ok', format('Payment received: %s is now live', coalesce(case when new.kind = 'ad' then 'your ad' else 'Featured' end, '')),
      format('We confirmed your payment of ৳%s (TrxID %s) for "%s".', to_char(new.amount, 'FM99,99,99,990'), new.trx_id, coalesce(new.item_title, '')),
      case when new.kind = 'ad' then 'seller.html#ads' else 'seller.html#featured' end, 'payment:' || new.id);
  elsif new.status = 'rejected' then
    perform public.notify(new.seller_id, 'payment_rejected', 'Payment not accepted',
      format('Your payment for "%s" (TrxID %s) was not accepted: %s Please check and pay again.', coalesce(new.item_title, ''), new.trx_id, coalesce(new.reject_reason, '')),
      case when new.kind = 'ad' then 'seller.html#ads' else 'seller.html#featured' end, 'payment:' || new.id);
  end if;
  return new;
end; $$;
drop trigger if exists alerts_payments on public.payments;
create trigger alerts_payments after update of status on public.payments for each row execute function public.alerts_payments();

-- Listings reviewed
create or replace function public.alerts_products()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare indiv boolean;
begin
  if new.status = old.status or new.status not in ('approved', 'rejected') or old.status = 'draft' then return new; end if;
  indiv := exists (select 1 from public.profiles where id = new.seller_id and role = 'individual');
  if new.status = 'approved' then
    perform public.notify(new.seller_id, 'listing_approved', format('Your listing is live: %s', new.title),
      'Buyers can now find it on RGBKart.', 'product.html?id=' || new.id, 'product:' || new.id);
  else
    perform public.notify(new.seller_id, 'listing_rejected', format('Listing not approved: %s', new.title),
      format('Reason: %s Fix it and send it again.', coalesce(new.review_note, '')), case when indiv then 'sell.html' else 'seller.html#products' end, 'product:' || new.id);
  end if;
  return new;
end; $$;
drop trigger if exists alerts_products on public.products;
create trigger alerts_products after update of status on public.products for each row execute function public.alerts_products();

-- Shop approved / not approved (shops only; one-time sellers are approved automatically)
create or replace function public.alerts_shops()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if new.status = old.status or exists (select 1 from public.profiles where id = new.user_id and role = 'individual') then return new; end if;
  if new.status = 'approved' then
    perform public.notify(new.user_id, 'shop_approved', format('Your shop %s is approved', new.shop_name), 'You can now add products in Seller Center.', 'seller.html', 'shop:' || new.user_id);
  elsif new.status = 'rejected' then
    perform public.notify(new.user_id, 'shop_rejected', format('Your shop %s was not approved', new.shop_name), 'Please contact RGBKart for details.', 'seller.html', 'shop:' || new.user_id);
  end if;
  return new;
end; $$;
drop trigger if exists alerts_shops on public.seller_details;
create trigger alerts_shops after update of status on public.seller_details for each row execute function public.alerts_shops();

-- New message (at most one alert per conversation every 30 minutes)
create or replace function public.alerts_messages()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare c record; who uuid; sender text;
begin
  select * into c from public.conversations where id = new.conversation_id;
  who := case when new.sender_id = c.buyer_id then c.seller_id else c.buyer_id end;
  sender := case when new.sender_id = c.buyer_id then c.buyer_name else coalesce((select shop_name from public.seller_details where user_id = c.seller_id), 'The seller') end;
  if exists (select 1 from public.notifications where user_id = who and ref = 'conv:' || c.id and created_at > now() - interval '30 minutes') then return new; end if;
  perform public.notify(who, 'message', format('New message from %s', sender),
    format('About "%s": %s', c.product_title, left(new.body, 200)), 'messages.html?c=' || c.id, 'conv:' || c.id);
  return new;
end; $$;
drop trigger if exists alerts_messages on public.messages;
create trigger alerts_messages after insert on public.messages for each row execute function public.alerts_messages();

-- 4. Reminders: Featured or ad ends in 2 days (called by the sender every few minutes) ---------------------------
alter table public.featured_requests add column if not exists reminded_at timestamptz;
alter table public.ads add column if not exists reminded_at timestamptz;

create or replace function public.queue_reminders()
returns integer language plpgsql security definer set search_path = ''
as $$
declare r record; n int := 0;
begin
  for r in select f.id, f.seller_id, f.ends_at, p.title from public.featured_requests f join public.products p on p.id = f.product_id
           where f.status = 'active' and f.reminded_at is null and not f.is_complimentary and f.ends_at between now() and now() + interval '2 days' loop
    perform public.notify(r.seller_id, 'featured_ending', format('Featured ends soon: %s', r.title),
      format('Featured ends on %s. Renew it in Seller Center to stay at the top.', to_char(r.ends_at at time zone 'Asia/Dhaka', 'DD Mon YYYY')), 'seller.html#featured', 'featured:' || r.id);
    update public.featured_requests set reminded_at = now() where id = r.id; n := n + 1;
  end loop;
  for r in select a.id, a.seller_id, a.ends_on, a.title from public.ads a
           where a.seller_id is not null and a.is_active and a.payment_status = 'paid' and a.reminded_at is null
             and a.ends_on between (now() at time zone 'Asia/Dhaka')::date and (now() at time zone 'Asia/Dhaka')::date + 2 loop
    perform public.notify(r.seller_id, 'ad_ending', format('Your ad ends soon: %s', r.title),
      format('Your ad runs until %s. Book a new one in Seller Center → Advertise.', to_char(r.ends_on, 'DD Mon YYYY')), 'seller.html#ads', 'ad:' || r.id);
    update public.ads set reminded_at = now() where id = r.id; n := n + 1;
  end loop;
  return n;
end; $$;
revoke execute on function public.queue_reminders() from public, anon, authenticated;
grant  execute on function public.queue_reminders() to service_role;

-- The sender takes a batch of emails to send (only the sender, using the service key, can call this)
create or replace function public.take_pending_alerts(p_limit integer default 40)
returns setof public.notifications language sql security definer set search_path = ''
as $$
  update public.notifications set attempts = attempts + 1
   where id in (select id from public.notifications where email_status = 'pending' and attempts < 5 and email is not null
                order by created_at limit greatest(1, least(coalesce(p_limit, 40), 100)) for update skip locked)
  returning *
$$;
revoke execute on function public.take_pending_alerts(integer) from public, anon, authenticated;
grant  execute on function public.take_pending_alerts(integer) to service_role;

create or replace function public.alert_sent(p_id bigint, p_ok boolean, p_error text default null)
returns void language sql security definer set search_path = ''
as $$
  update public.notifications
     set email_status = case when p_ok then 'sent' when attempts >= 5 then 'failed' else 'pending' end,
         email_sent_at = case when p_ok then now() else email_sent_at end,
         email_error = case when p_ok then null else left(p_error, 300) end
   where id = p_id
$$;
revoke execute on function public.alert_sent(bigint, boolean, text) from public, anon, authenticated;
grant  execute on function public.alert_sent(bigint, boolean, text) to service_role;

-- Admin can see how emails are doing
create or replace function public.admin_alert_stats()
returns jsonb language sql stable security definer set search_path = ''
as $$
  select case when public.has_staff_role(array['master_admin', 'co_admin']) then jsonb_build_object(
    'pending', (select count(*) from public.notifications where email_status = 'pending'),
    'sent_24h', (select count(*) from public.notifications where email_status = 'sent' and email_sent_at > now() - interval '1 day'),
    'failed', (select count(*) from public.notifications where email_status = 'failed'),
    'last_sent', (select max(email_sent_at) from public.notifications),
    'last_error', (select email_error from public.notifications where email_error is not null order by created_at desc limit 1)) end
$$;
grant execute on function public.admin_alert_stats() to authenticated;

-- 5. Check ---------------------------------------------------------------------------------------------------------
select to_regclass('public.notifications') is not null as alerts_ready,
       (select count(*) from pg_trigger where tgname like 'alerts_%') as alert_triggers;
