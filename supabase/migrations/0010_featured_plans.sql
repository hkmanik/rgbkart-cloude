-- Featured plans (plan 5.4): price, duration and benefits of a Featured listing, set by the admin.
-- Run once in Supabase → SQL Editor, AFTER shop_settings.sql. Safe to run again.
--
-- Sellers pick a plan when adding a product. The price and days are copied from the plan
-- at that moment, so changing a plan later never changes what a seller already agreed to.

-- 1. Plans --------------------------------------------------------------------

create table if not exists public.featured_plans (
  id          bigint generated by default as identity primary key,
  name        text not null unique check (char_length(trim(name)) between 2 and 60),
  price       numeric(10, 2) not null check (price >= 0),          -- in Taka (৳)
  days        integer not null check (days between 1 and 365),
  placement   text not null default 'home_and_category' check (placement in ('home', 'category', 'home_and_category')),
  benefits    text[] not null default '{}',
  is_active   boolean not null default true,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

alter table public.featured_plans enable row level security;
revoke all on public.featured_plans from anon, authenticated;
grant select on public.featured_plans to anon, authenticated;
grant insert, update, delete on public.featured_plans to authenticated;

drop policy if exists "Anyone reads active plans" on public.featured_plans;
create policy "Anyone reads active plans" on public.featured_plans for select to anon, authenticated
  using (is_active or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));
drop policy if exists "Admins manage plans" on public.featured_plans;
create policy "Admins manage plans" on public.featured_plans for all to authenticated
  using (public.has_staff_role(array['master_admin', 'co_admin']))
  with check (public.has_staff_role(array['master_admin', 'co_admin']));

