-- 2. Link requests to a plan ----------------------------------------------------

alter table public.featured_requests
  add column if not exists plan_id bigint references public.featured_plans (id) on delete set null,
  add column if not exists price   numeric(10, 2);

alter table public.featured_requests drop constraint if exists featured_requests_placement_check;
alter table public.featured_requests drop constraint if exists featured_requests_days_check;
alter table public.featured_requests drop constraint if exists featured_requests_rules;
alter table public.featured_requests add constraint featured_requests_rules check (
  placement in ('home', 'category', 'home_and_category') and days between 1 and 365 and (price is null or price >= 0));

-- Price, days and placement always come from the plan, never from the seller.
create or replace function public.featured_requests_from_plan()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare pl record;
begin
  if new.plan_id is null then raise exception 'Choose a Featured plan'; end if;
  select * into pl from public.featured_plans where id = new.plan_id and is_active;
  if pl.id is null then raise exception 'That Featured plan is no longer available'; end if;
  new.price := pl.price; new.days := pl.days; new.placement := pl.placement;
  new.status := 'awaiting_payment'; new.starts_at := null; new.ends_at := null;
  return new;
end; $$;

drop trigger if exists featured_requests_from_plan on public.featured_requests;
create trigger featured_requests_from_plan before insert on public.featured_requests
  for each row execute function public.featured_requests_from_plan();

revoke insert on public.featured_requests from authenticated;
grant insert (product_id, plan_id) on public.featured_requests to authenticated;

-- 3. Check ---------------------------------------------------------------------
select name, price as price_taka, days, is_active from public.featured_plans order by sort_order, id;
