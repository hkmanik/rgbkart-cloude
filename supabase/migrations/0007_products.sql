-- Products and product photos (plan 1.4).
-- Run once in Supabase → SQL Editor, AFTER catalog.sql and catalog_seed.sql. Safe to run again.
--
-- How a product moves:  draft → (seller submits) → pending → (staff reviews) → approved / rejected
--                        approved products are what shoppers see. Sellers can archive (hide) their own.
-- Who can do what:
--   Approved sellers  create and edit their own products and upload photos to their own folder.
--   Shoppers          see approved products only.
--   Staff             see everything; Master Admin, Co-admin and Editor approve or reject.

-- 1. Helpers --------------------------------------------------------------

create or replace function public.is_approved_seller()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    join public.seller_details s on s.user_id = p.id
    where p.id = auth.uid() and p.role = 'seller' and s.status = 'approved')
$$;

-- All attributes a category asks for, including those inherited from parent categories.
create or replace function public.category_effective_attributes(p_category bigint)
returns table (attribute_id bigint, is_required boolean, from_category bigint, depth int)
language sql stable set search_path = ''
as $$
  with recursive chain as (
    select id, parent_id, 0 as depth from public.categories where id = p_category
    union all
    select c.id, c.parent_id, chain.depth + 1 from public.categories c join chain on c.id = chain.parent_id
  )
  select distinct on (ca.attribute_id) ca.attribute_id, ca.is_required, ca.category_id, chain.depth
  from chain join public.category_attributes ca on ca.category_id = chain.id
  order by ca.attribute_id, chain.depth
$$;

grant execute on function public.is_approved_seller() to authenticated;
grant execute on function public.category_effective_attributes(bigint) to anon, authenticated;

-- 2. Products --------------------------------------------------------------

create table if not exists public.products (
  id                bigint generated by default as identity primary key,
  seller_id         uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  category_id       bigint not null references public.categories (id) on delete restrict,
  title             text not null check (char_length(trim(title)) between 3 and 200),
  slug              text unique,
  description       text check (description is null or char_length(description) <= 5000),
  price             numeric(12, 2) not null check (price > 0),                    -- in Taka (৳)
  stock             integer not null default 0 check (stock >= 0),
  sku               text check (sku is null or char_length(sku) <= 60),          -- seller's own product code
  status            text not null default 'draft'
                    check (status in ('draft', 'pending', 'approved', 'rejected', 'archived')),
  review_note       text,                                                        -- reason shown to the seller when rejected
  reviewed_by       uuid references auth.users (id) on delete set null,
  reviewed_at       timestamptz,
  is_featured       boolean not null default false,                              -- set by paid packages later (plan 5.4)
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  published_at      timestamptz
);
create index if not exists products_seller_idx   on public.products (seller_id, status);
create index if not exists products_category_idx on public.products (category_id, status);
create index if not exists products_status_idx   on public.products (status, created_at desc);

create table if not exists public.product_images (
  id            bigint generated by default as identity primary key,
  product_id    bigint not null references public.products (id) on delete cascade,
  storage_path  text not null,          -- path inside the product-images bucket: <seller id>/<file name>
  alt_text      text,
  sort_order    integer not null default 0,  -- the lowest number is the main photo
  created_at    timestamptz not null default now(),
  unique (product_id, storage_path)
);
create index if not exists product_images_product_idx on public.product_images (product_id, sort_order);

-- One row per chosen value. "Several options" attributes get one row per option.
create table if not exists public.product_attribute_values (
  id            bigint generated by default as identity primary key,
  product_id    bigint not null references public.products (id) on delete cascade,
  attribute_id  bigint not null references public.attributes (id) on delete cascade,
  option_id     bigint references public.attribute_options (id) on delete cascade,
  bool_value    boolean,
  check ((option_id is not null) <> (bool_value is not null))
);
create unique index if not exists pav_option_uniq on public.product_attribute_values (product_id, attribute_id, option_id) where option_id is not null;
create unique index if not exists pav_bool_uniq   on public.product_attribute_values (product_id, attribute_id) where bool_value is not null;
create index if not exists pav_filter_idx on public.product_attribute_values (attribute_id, option_id);

-- 3. Automatic rules ------------------------------------------------------

-- Web address, timestamps, and: when a seller changes the title, description or category
-- of an approved product, it goes back to review.
create or replace function public.products_before_write()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare base text;
begin
  if tg_op = 'INSERT' then
    base := trim(both '-' from regexp_replace(lower(new.title), '[^a-z0-9]+', '-', 'g'));
    new.slug := left(coalesce(nullif(base, ''), 'product'), 80) || '-' || new.id;
    new.created_at := now();
  else
    new.slug := old.slug;
  end if;
  new.updated_at := now();

  if tg_op = 'UPDATE' and old.status = 'approved'
     and not public.has_staff_role(array['master_admin', 'co_admin', 'editor'])
     and (new.title is distinct from old.title
          or new.description is distinct from old.description
          or new.category_id is distinct from old.category_id) then
    new.status := 'pending';
  end if;
  return new;
end; $$;

drop trigger if exists products_before_write on public.products;
create trigger products_before_write before insert or update on public.products
  for each row execute function public.products_before_write();

-- A chosen option must belong to the attribute, and the attribute must apply to the product's category.
create or replace function public.pav_check()
returns trigger language plpgsql set search_path = ''
as $$
declare cat bigint; t text;
begin
  select category_id into cat from public.products where id = new.product_id;
  if not exists (select 1 from public.category_effective_attributes(cat) e where e.attribute_id = new.attribute_id) then
    raise exception 'This attribute doesn''t apply to the product''s category';
  end if;
  select input_type into t from public.attributes where id = new.attribute_id;
  if t = 'boolean' and new.bool_value is null then raise exception 'Choose Yes or No'; end if;
  if t <> 'boolean' and new.option_id is null then raise exception 'Choose an option from the list'; end if;
  if new.option_id is not null and not exists (
       select 1 from public.attribute_options o where o.id = new.option_id and o.attribute_id = new.attribute_id) then
    raise exception 'That option doesn''t belong to this attribute';
  end if;
  if t in ('select', 'color') and exists (
       select 1 from public.product_attribute_values v
       where v.product_id = new.product_id and v.attribute_id = new.attribute_id and v.id <> coalesce(new.id, -1)) then
    raise exception 'Only one option can be chosen for this attribute';
  end if;
  return new;
end; $$;

drop trigger if exists pav_check on public.product_attribute_values;
create trigger pav_check before insert or update on public.product_attribute_values
  for each row execute function public.pav_check();

-- 4. Status changes -------------------------------------------------------

-- Seller sends a product for review. Checks it is complete first.
create or replace function public.submit_product(p_product bigint)
returns text language plpgsql security definer set search_path = ''
as $$
declare p record; missing text;
begin
  select * into p from public.products where id = p_product and seller_id = auth.uid();
  if p.id is null then raise exception 'Product not found'; end if;
  if not public.is_approved_seller() then raise exception 'Your shop must be approved before you can list products'; end if;
  if p.status not in ('draft', 'rejected', 'archived') then raise exception 'This product is already % ', p.status; end if;
  if not exists (select 1 from public.product_images where product_id = p.id) then
    raise exception 'Add at least one photo';
  end if;
  select string_agg(a.name, ', ' order by a.name) into missing
    from public.category_effective_attributes(p.category_id) e
    join public.attributes a on a.id = e.attribute_id
   where e.is_required
     and not exists (select 1 from public.product_attribute_values v where v.product_id = p.id and v.attribute_id = e.attribute_id);
  if missing is not null then raise exception 'Fill in the required details: %', missing; end if;

  update public.products set status = 'pending', review_note = null where id = p.id;
  return 'pending';
end; $$;

-- Seller hides a product, or brings it back as a draft.
create or replace function public.archive_product(p_product bigint, p_archive boolean)
returns text language plpgsql security definer set search_path = ''
as $$
declare s text;
begin
  select status into s from public.products where id = p_product and seller_id = auth.uid();
  if s is null then raise exception 'Product not found'; end if;
  update public.products set status = case when p_archive then 'archived' else 'draft' end where id = p_product;
  return case when p_archive then 'archived' else 'draft' end;
end; $$;

-- Staff approve or reject. A reason is required when rejecting.
create or replace function public.review_product(p_product bigint, p_status text, p_note text default null)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if not public.has_staff_role(array['master_admin', 'co_admin', 'editor']) then
    raise exception 'You don''t have permission to review products';
  end if;
  if p_status not in ('approved', 'rejected', 'pending') then raise exception 'Invalid status'; end if;
  if p_status = 'rejected' and coalesce(trim(p_note), '') = '' then raise exception 'Give the seller a reason for rejecting'; end if;
  update public.products
     set status = p_status,
         review_note = case when p_status = 'rejected' then trim(p_note) else null end,
         reviewed_by = auth.uid(), reviewed_at = now(),
         published_at = case when p_status = 'approved' then coalesce(published_at, now()) else published_at end
   where id = p_product;
  if not found then raise exception 'Product not found'; end if;
end; $$;

revoke execute on function public.submit_product(bigint), public.archive_product(bigint, boolean), public.review_product(bigint, text, text) from public, anon;
grant  execute on function public.submit_product(bigint), public.archive_product(bigint, boolean), public.review_product(bigint, text, text) to authenticated;

-- 5. Security -------------------------------------------------------------

alter table public.products                 enable row level security;
alter table public.product_images           enable row level security;
alter table public.product_attribute_values enable row level security;

revoke all on public.products, public.product_images, public.product_attribute_values from anon, authenticated;
grant select on public.products, public.product_images, public.product_attribute_values to anon, authenticated;
grant insert (category_id, title, description, price, stock, sku) on public.products to authenticated;
grant update (category_id, title, description, price, stock, sku) on public.products to authenticated;
grant delete on public.products to authenticated;
grant insert, update, delete on public.product_images, public.product_attribute_values to authenticated;

-- products
drop policy if exists "Read products" on public.products;
create policy "Read products" on public.products for select to anon, authenticated
  using (status = 'approved' or seller_id = auth.uid()
         or public.has_staff_role(array['master_admin', 'co_admin', 'editor']));

drop policy if exists "Approved sellers add products" on public.products;
create policy "Approved sellers add products" on public.products for insert to authenticated
  with check (seller_id = auth.uid() and status = 'draft' and public.is_approved_seller());

drop policy if exists "Sellers edit own products" on public.products;
create policy "Sellers edit own products" on public.products for update to authenticated
  using (seller_id = auth.uid() and public.is_approved_seller())
  with check (seller_id = auth.uid());

drop policy if exists "Sellers and admins delete products" on public.products;
create policy "Sellers and admins delete products" on public.products for delete to authenticated
  using (seller_id = auth.uid() or public.has_staff_role(array['master_admin', 'co_admin']));

-- photos and attribute values follow their product
do $$
declare t text;
begin
  foreach t in array array['product_images', 'product_attribute_values'] loop
    execute format('drop policy if exists "Read with product" on public.%I', t);
    execute format('create policy "Read with product" on public.%I for select to anon, authenticated
                      using (exists (select 1 from public.products p where p.id = product_id))', t);
    execute format('drop policy if exists "Seller edits own" on public.%I', t);
    execute format('create policy "Seller edits own" on public.%I for all to authenticated
                      using (exists (select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid()))
                      with check (exists (select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid())
                                  and public.is_approved_seller())', t);
  end loop;
end $$;

-- 6. Photo storage ---------------------------------------------------------
-- Public bucket: anyone can view a photo by its link. Only approved sellers can upload,
-- and only into their own folder (<their user id>/...). Max 5 MB; JPG, PNG or WebP.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-images', 'product-images', true, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = true, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Product photos are public" on storage.objects;
create policy "Product photos are public" on storage.objects for select to anon, authenticated
  using (bucket_id = 'product-images');

drop policy if exists "Sellers upload to own folder" on storage.objects;
create policy "Sellers upload to own folder" on storage.objects for insert to authenticated
  with check (bucket_id = 'product-images' and (storage.foldername(name))[1] = auth.uid()::text and public.is_approved_seller());

drop policy if exists "Sellers change own photos" on storage.objects;
create policy "Sellers change own photos" on storage.objects for update to authenticated
  using (bucket_id = 'product-images' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "Sellers and admins delete photos" on storage.objects;
create policy "Sellers and admins delete photos" on storage.objects for delete to authenticated
  using (bucket_id = 'product-images'
         and ((storage.foldername(name))[1] = auth.uid()::text or public.has_staff_role(array['master_admin', 'co_admin'])));

