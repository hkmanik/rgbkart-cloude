-- More product options (plan 1.5): Downloadable, Service, Gift card / voucher,
-- Pre-order, Wholesale price and Cash on delivery on/off.
-- Run once in Supabase → SQL Editor, AFTER featured_plans.sql. Safe to run again.

-- 1. New product columns ----------------------------------------------------

alter table public.products
  add column if not exists is_downloadable          boolean not null default false,
  add column if not exists download_limit           integer,          -- times a buyer can download; empty = unlimited
  add column if not exists download_expiry_days     integer,          -- days the link works after purchase; empty = never expires
  add column if not exists is_service               boolean not null default false,
  add column if not exists service_mode             text,             -- at_customer / at_shop / online
  add column if not exists service_duration         text,
  add column if not exists is_gift_card             boolean not null default false,
  add column if not exists gift_card_validity_days  integer,
  add column if not exists is_preorder              boolean not null default false,
  add column if not exists preorder_date            date,             -- expected arrival / dispatch date
  add column if not exists preorder_advance_percent integer,          -- % paid when ordering; 0 = pay on delivery
  add column if not exists cod_allowed              boolean not null default true;

alter table public.products drop constraint if exists products_options_rules;
alter table public.products add constraint products_options_rules check (
      (download_limit is null or download_limit between 1 and 100)
  and (download_expiry_days is null or download_expiry_days between 1 and 3650)
  and (service_mode is null or service_mode in ('at_customer', 'at_shop', 'online'))
  and (service_duration is null or service_duration in ('30_min', '1_hour', '2_hours', 'half_day', 'full_day', 'multi_day'))
  and (gift_card_validity_days is null or gift_card_validity_days between 30 and 1095)
  and (not is_gift_card or (not is_downloadable and not is_service and product_type = 'simple'))
  and (not is_preorder or preorder_date is not null)
  and (preorder_advance_percent is null or preorder_advance_percent between 0 and 100)
);

grant insert (is_downloadable, download_limit, download_expiry_days, is_service, service_mode, service_duration,
              is_gift_card, gift_card_validity_days, is_preorder, preorder_date, preorder_advance_percent, cod_allowed)
  on public.products to authenticated;
grant update (is_downloadable, download_limit, download_expiry_days, is_service, service_mode, service_duration,
              is_gift_card, gift_card_validity_days, is_preorder, preorder_date, preorder_advance_percent, cod_allowed)
  on public.products to authenticated;

-- 2. Wholesale price tiers (e.g. 10+ pieces at ৳450 each) ---------------------

create table if not exists public.product_price_tiers (
  product_id  bigint not null references public.products (id) on delete cascade,
  min_qty     integer not null check (min_qty between 2 and 100000),
  unit_price  numeric(12, 2) not null check (unit_price > 0),
  primary key (product_id, min_qty)
);

-- 3. Download files (private; buyers get a temporary link after paying) -------

create table if not exists public.product_downloads (
  id            bigint generated by default as identity primary key,
  product_id    bigint not null references public.products (id) on delete cascade,
  file_name     text not null check (char_length(file_name) between 1 and 200),
  storage_path  text not null,          -- <seller id>/<product id>/<file> in the product-downloads bucket
  size_bytes    bigint,
  sort_order    integer not null default 0,
  created_at    timestamptz not null default now(),
  unique (product_id, storage_path)
);

-- 4. Security -------------------------------------------------------------------

alter table public.product_price_tiers enable row level security;
alter table public.product_downloads   enable row level security;
revoke all on public.product_price_tiers, public.product_downloads from anon, authenticated;
grant select on public.product_price_tiers to anon, authenticated;
grant insert, update, delete on public.product_price_tiers to authenticated;
grant select, insert, update, delete on public.product_downloads to authenticated;

drop policy if exists "Read with product" on public.product_price_tiers;
create policy "Read with product" on public.product_price_tiers for select to anon, authenticated
  using (exists (select 1 from public.products p where p.id = product_id));
drop policy if exists "Seller edits own" on public.product_price_tiers;
create policy "Seller edits own" on public.product_price_tiers for all to authenticated
  using (exists (select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid()))
  with check (exists (select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid()) and public.is_approved_seller());

-- Shoppers can see the file NAMES (to know what they'll get), never the files themselves.
drop policy if exists "Read file list with product" on public.product_downloads;
create policy "Read file list with product" on public.product_downloads for select to anon, authenticated
  using (exists (select 1 from public.products p where p.id = product_id));
grant select (id, product_id, file_name, size_bytes, sort_order) on public.product_downloads to anon;
drop policy if exists "Seller edits own" on public.product_downloads;
create policy "Seller edits own" on public.product_downloads for all to authenticated
  using (exists (select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid()))
  with check (exists (select 1 from public.products p where p.id = product_id and p.seller_id = auth.uid()) and public.is_approved_seller());

-- Private bucket: up to 50 MB per file, any file type. Only the seller (and Master Admin / Co-admin) can open files.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-downloads', 'product-downloads', false, 52428800, null)
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = null;

drop policy if exists "Sellers upload own downloads" on storage.objects;
create policy "Sellers upload own downloads" on storage.objects for insert to authenticated
  with check (bucket_id = 'product-downloads' and (storage.foldername(name))[1] = auth.uid()::text and public.is_approved_seller());
drop policy if exists "Sellers and admins read downloads" on storage.objects;
create policy "Sellers and admins read downloads" on storage.objects for select to authenticated
  using (bucket_id = 'product-downloads'
         and ((storage.foldername(name))[1] = auth.uid()::text or public.has_staff_role(array['master_admin', 'co_admin'])));
drop policy if exists "Sellers delete own downloads" on storage.objects;
create policy "Sellers delete own downloads" on storage.objects for delete to authenticated
  using (bucket_id = 'product-downloads'
         and ((storage.foldername(name))[1] = auth.uid()::text or public.has_staff_role(array['master_admin', 'co_admin'])));

-- 5. Sending for review: extra checks ---------------------------------------------

create or replace function public.submit_product(p_product bigint)
returns text language plpgsql security definer set search_path = ''
as $$
declare p record; missing text;
begin
  select * into p from public.products where id = p_product and seller_id = auth.uid();
  if p.id is null then raise exception 'Product not found'; end if;
  if not public.is_approved_seller() then raise exception 'Your shop must be approved before you can list products'; end if;
  if p.status not in ('draft', 'rejected', 'archived') then raise exception 'This product is already %', p.status; end if;
  if not exists (select 1 from public.product_images where product_id = p.id) then
    raise exception 'Add a main image';
  end if;
  if p.is_downloadable and not exists (select 1 from public.product_downloads where product_id = p.id) then
    raise exception 'Upload the file buyers will download';
  end if;
  if p.is_service and p.service_mode is null then raise exception 'Choose where the service happens'; end if;
  if p.is_preorder and p.preorder_date < current_date then raise exception 'The pre-order date has passed. Choose a new date'; end if;
  if p.product_type = 'variable' then
    if not exists (select 1 from public.product_variations where product_id = p.id and is_active) then
      raise exception 'Add at least one variation, or switch to a simple product';
    end if;
    if p.listing_type <> 'free' and exists (select 1 from public.product_variations where product_id = p.id and is_active and price <= 0) then
      raise exception 'Every active variation needs a price';
    end if;
  end if;
  if exists (select 1 from public.product_price_tiers t where t.product_id = p.id and t.unit_price >= p.price) then
    raise exception 'Wholesale prices must be lower than the regular price';
  end if;
  select string_agg(a.name, ', ' order by a.name) into missing
    from public.category_effective_attributes(p.category_id) e
    join public.attributes a on a.id = e.attribute_id
   where e.is_required
     and not exists (select 1 from public.product_attribute_values v where v.product_id = p.id and v.attribute_id = e.attribute_id)
     and not exists (select 1 from public.product_variations pv join public.product_variation_options o on o.variation_id = pv.id
                     where pv.product_id = p.id and pv.is_active and o.attribute_id = e.attribute_id);
  if missing is not null then raise exception 'Fill in the required details: %', missing; end if;

  update public.products set status = 'pending', review_note = null where id = p.id;
  return 'pending';
end; $$;

-- 6. Check -----------------------------------------------------------------------
select to_regclass('public.product_price_tiers') is not null as wholesale_ready,
       to_regclass('public.product_downloads') is not null as downloads_ready,
       (select public from storage.buckets where id = 'product-downloads') as download_bucket_public;
