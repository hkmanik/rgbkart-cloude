$pg$Everything you need to buy or sell on RGBKart, step by step. Still stuck? See the Contact page and we will help.

## How to buy
1. **Find a product.** Use the search box at the top, open "All categories", or browse Deals and Featured products.
2. **Choose and add to cart.** Pick the size, colour or version if the product has them, then tap **Add to cart**. One cart can hold products from several shops.
3. **Choose delivery.** In the cart, pick a delivery method for each shop (inside Dhaka, outside Dhaka or store pickup). The delivery fee is shown before you order.
4. **Place your order.** Enter your name, phone and address. You do not need an account: you can order as a guest, or sign in with Google or Facebook to keep your orders in one place.
5. **Pay when it arrives.** You pay the shop's delivery person in cash.

## How Cash on Delivery works
- You pay nothing in advance. Check the parcel, then pay the amount shown on your order.
- RGBKart never takes your money. You pay the shop directly.
- For your safety, a first order and very large orders have a limit. You will see it at checkout.

## Track, cancel or return an order
- Open **My orders** to see each step: confirmed, packed, shipped, delivered.
- You can cancel an order yourself until the shop confirms it. After that, use **Ask the shop to cancel**.
- If an item is damaged, wrong or not as described, use **Return this item** in My orders within the shop's return period. You can add up to 3 photos.
- After delivery you can rate the shop and the product. Only real buyers can write reviews.

## Stay safe
- Prefer shops with the **✓ Verified shop** badge and good reviews.
- Never send money in advance to someone who contacts you outside RGBKart.
- See something wrong? Use **⚑ Report** on the product or shop page. Our team checks every report.

## How to open a shop
1. Tap **Open a shop** (on phones: **Store**) at the top of any page.
2. Fill in your shop name, phone, address and district, and agree to the seller rules.
3. Our team checks your shop, usually quickly. You will get a message when it is approved.
4. Open **Seller Center** and tap **+ Add product**: add photos, the price and the details. Every listing is checked before shoppers see it.
5. When an order comes in, confirm it, pack it and send it with your delivery partner. The buyer pays you in cash on delivery.

## What a shop gets, free
- **No commission.** Opening a shop is free and RGBKart takes no cut from your sales.
- **Your own shop page and link**, with your banner, logo, contact details, reviews and all your products. No domain, hosting or website needed.
- **Seller Center:** products, orders, printing of invoices and delivery labels, messages, reviews, returns, coupons and your own delivery rates.
- **Get verified:** send your NID or trade licence to earn the ✓ Verified shop badge.

## Grow with Featured and ads
- **Featured listing:** your product is shown first with a gold ★ Featured badge for the days you choose.
- **Advertisements:** book a picture banner or pop-up on RGBKart from Seller Center → Advertise.
- Pay the small fee by bKash, Nagad or Upay and enter the transaction ID (TrxID). Our team checks it and switches it on.

## Sell one item without a shop
1. Tap **+ Sell** (or "Sell an item") and fill in the form. No shop needed.
2. Choose **Free** (buyers message you on RGBKart; your phone number stays private) or **Featured** (shown first, buyers can call or WhatsApp you).
3. Our team checks the listing and puts it live. You can have up to 5 listings.

